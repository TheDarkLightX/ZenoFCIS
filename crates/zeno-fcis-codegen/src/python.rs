/// Rejects schema names that would not be distinct, unshadowed Python names in
/// the generated module.
///
/// Type names become module globals (with `<Map>Entry` companions and
/// `TYPE_`/`FIELD_`/`VARIANT_` constants); record field names become
/// `__init__` parameters and instance attributes; variant names appear only in
/// string literals and constants.
fn validate_python_names(schema: &Schema, spec: &GenerationSpec) -> Result<(), CodegenError> {
    // The adapter imports the sibling `zcve` codec module.
    if spec.python_module() == "zcve" {
        return Err(CodegenError::InvalidModuleName);
    }
    let mut globals: BTreeSet<String> = PYTHON_MODULE_NAMES
        .iter()
        .map(|name| (*name).to_owned())
        .collect();
    for definition in schema.types() {
        let name = python_name(definition.name().as_str())?;
        // Leading `__` names are mangled when referenced inside class bodies.
        if name.starts_with("__") || PYTHON_SHADOWED_NAMES.contains(&name.as_str()) {
            return Err(CodegenError::InvalidIdentifier);
        }
        let upper = name.to_ascii_uppercase();
        let mut generated = vec![format!("TYPE_{upper}")];
        match definition.kind() {
            TypeKind::Record { fields } => {
                for field in fields.iter() {
                    let field_name = python_name(field.name().as_str())?;
                    // `self` is the `__init__` receiver; the method names would
                    // be shadowed by instance attributes; `__` names are mangled
                    // or special.
                    if field_name.starts_with("__")
                        || ["self", "to_value", "try_from_value"].contains(&field_name.as_str())
                    {
                        return Err(CodegenError::InvalidIdentifier);
                    }
                    generated.push(format!("FIELD_{upper}_{}", field_name.to_ascii_uppercase()));
                }
            }
            TypeKind::Enum { variants } => {
                for variant in variants.iter() {
                    let variant_name = python_name(variant.name().as_str())?;
                    generated.push(format!(
                        "VARIANT_{upper}_{}",
                        variant_name.to_ascii_uppercase()
                    ));
                }
            }
            TypeKind::Sum { variants } => {
                for variant in variants.iter() {
                    let variant_name = python_name(variant.name().as_str())?;
                    generated.push(format!(
                        "VARIANT_{upper}_{}",
                        variant_name.to_ascii_uppercase()
                    ));
                }
            }
            TypeKind::Map { .. } => generated.push(format!("{name}Entry")),
            _ => {}
        }
        generated.push(name);
        for global in generated {
            if !globals.insert(global) {
                return Err(CodegenError::InvalidIdentifier);
            }
        }
    }
    Ok(())
}

fn python_name(value: &str) -> Result<String, CodegenError> {
    const RESERVED: &[&str] = &[
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    if RESERVED.contains(&value) {
        return Err(CodegenError::InvalidIdentifier);
    }
    Ok(value.to_owned())
}

