fn emit_enum(
    output: &mut String,
    definition: &TypeDef,
    name: &str,
    variants: &[zeno_fcis_schema::EnumVariantDef],
) {
    let type_const = format!("TYPE_{}", name.to_ascii_uppercase());
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    _BY_NAME = {{}}");
    let _ = writeln!(output, "    _BY_ORD = {{}}");
    let _ = writeln!(
        output,
        "    def __init__(self, variant): self.variant = variant"
    );
    let _ = writeln!(output, "    def to_value(self):");
    emit_variant_name_check(output);
    let _ = writeln!(
        output,
        "        return (\"enum\", {type_const}, self._BY_NAME[self.variant])"
    );
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(
        output,
        "        if not (_is_tagged(v, \"enum\", 3) and type(v[1]) is int and v[1] == {type_const}): raise AdapterError(\"type_mismatch\")"
    );
    let _ = writeln!(output, "        ord_ = v[2]");
    let _ = writeln!(output, "        {}", exact_type_check("ord_", "int"));
    let _ = writeln!(
        output,
        "        if ord_ not in cls._BY_ORD: raise AdapterError(\"unknown_variant\")"
    );
    let _ = writeln!(output, "        return cls(cls._BY_ORD[ord_])\n");
    for variant in variants {
        let vname = variant.name().as_str();
        let vconst = format!(
            "VARIANT_{}_{}",
            name.to_ascii_uppercase(),
            vname.to_ascii_uppercase()
        );
        let _ = writeln!(output, "{name}._BY_NAME[\"{vname}\"] = {vconst}");
        let _ = writeln!(output, "{name}._BY_ORD[{vconst}] = \"{vname}\"");
    }
    output.push('\n');
    let _ = definition;
}

fn emit_tuple(
    output: &mut String,
    schema: &Schema,
    _definition: &TypeDef,
    name: &str,
    items: &[TypeId],
) {
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    def __init__(self, {}):", tuple_fields(items));
    for (index, _item) in items.iter().enumerate() {
        let _ = writeln!(output, "        self.field_{index} = field_{index}");
    }
    let _ = writeln!(output, "    def to_value(self):");
    let _ = writeln!(
        output,
        "        return (\"tuple\", [{}])",
        tuple_to_value(schema, items)
    );
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(output, "        {}", tagged_check("tuple", 2));
    let _ = writeln!(output, "        items = v[1]");
    let _ = writeln!(output, "        {}", exact_type_check("items", "list"));
    let _ = writeln!(
        output,
        "        if len(items) != {}: raise AdapterError(\"record_shape\")",
        items.len()
    );
    let mut calls = Vec::new();
    for (index, item) in items.iter().enumerate() {
        let item_name = resolve_type_name(schema, *item);
        calls.push(format!("{item_name}.try_from_value(items[{index}])"));
    }
    let _ = writeln!(output, "        return cls({})", calls.join(", "));
    output.push('\n');
}

fn emit_record(
    output: &mut String,
    schema: &Schema,
    definition: &TypeDef,
    name: &str,
    fields: &[FieldDef],
) -> Result<(), CodegenError> {
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(
        output,
        "    def __init__(self, {}):",
        record_fields(fields)?
    );
    for field in fields {
        let fname = field.name().as_str();
        let _ = writeln!(output, "        self.{fname} = {fname}");
    }
    let _ = writeln!(output, "    def to_value(self):");
    let type_upper = name.to_ascii_uppercase();
    let mut to_value_parts = Vec::new();
    for field in fields {
        let fname = field.name().as_str();
        let fconst = format!("FIELD_{type_upper}_{}", fname.to_ascii_uppercase());
        let ftype = resolve_type_name(schema, field.type_id());
        to_value_parts.push(format!("({fconst}, _child_value(self.{fname}, {ftype}))"));
    }
    let _ = writeln!(
        output,
        "        return (\"record\", [{}])",
        to_value_parts.join(", ")
    );
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(output, "        {}", tagged_check("record", 2));
    let _ = writeln!(output, "        fields = v[1]");
    let _ = writeln!(output, "        {}", exact_type_check("fields", "list"));
    let _ = writeln!(
        output,
        "        if len(fields) != {}: raise AdapterError(\"record_shape\")",
        fields.len()
    );
    // Decoded children are collected positionally so schema field names are
    // never bound as locals that could shadow generated or builtin names.
    let _ = writeln!(output, "        values = []");
    for (index, field) in fields.iter().enumerate() {
        let fname = field.name().as_str();
        let fconst = format!("FIELD_{type_upper}_{}", fname.to_ascii_uppercase());
        let _ = writeln!(output, "        field = fields[{index}]");
        let _ = writeln!(
            output,
            "        if not _is_tuple(field, 2): raise AdapterError(\"type_mismatch\")"
        );
        let _ = writeln!(output, "        {}", exact_type_check("field[0]", "int"));
        let _ = writeln!(
            output,
            "        if field[0] != {fconst}: raise AdapterError(\"record_shape\")"
        );
        let ftype = resolve_type_name(schema, field.type_id());
        let _ = writeln!(
            output,
            "        values.append({ftype}.try_from_value(field[1]))"
        );
    }
    let _ = writeln!(output, "        return cls(*values)");
    output.push('\n');
    let _ = definition;
    Ok(())
}

fn emit_sum(
    output: &mut String,
    schema: &Schema,
    _definition: &TypeDef,
    name: &str,
    variants: &[zeno_fcis_schema::SumVariantDef],
) {
    let type_const = format!("TYPE_{}", name.to_ascii_uppercase());
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    _PAYLOAD = {{}}");
    let _ = writeln!(output, "    _BY_NAME = {{}}");
    let _ = writeln!(output, "    _BY_ORD = {{}}");
    let _ = writeln!(
        output,
        "    def __init__(self, variant, payload=None): self.variant = variant; self.payload = payload"
    );
    let _ = writeln!(output, "    def to_value(self):");
    emit_variant_name_check(output);
    let _ = writeln!(output, "        ord_ = self._BY_NAME[self.variant]");
    let _ = writeln!(output, "        ptype = self._PAYLOAD.get(self.variant)");
    let _ = writeln!(output, "        if ptype is None:");
    let _ = writeln!(
        output,
        "            if self.payload is not None: raise AdapterError(\"unexpected_payload\")"
    );
    let _ = writeln!(
        output,
        "            return (\"sum\", {type_const}, ord_, None)"
    );
    let _ = writeln!(
        output,
        "        if self.payload is None: raise AdapterError(\"missing_payload\")"
    );
    let _ = writeln!(
        output,
        "        return (\"sum\", {type_const}, ord_, _child_value(self.payload, ptype))"
    );
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(
        output,
        "        if not (_is_tagged(v, \"sum\", 4) and type(v[1]) is int and v[1] == {type_const}): raise AdapterError(\"type_mismatch\")"
    );
    let _ = writeln!(output, "        ord_ = v[2]; payload = v[3]");
    let _ = writeln!(output, "        {}", exact_type_check("ord_", "int"));
    let _ = writeln!(
        output,
        "        if ord_ not in cls._BY_ORD: raise AdapterError(\"unknown_variant\")"
    );
    let _ = writeln!(output, "        variant = cls._BY_ORD[ord_]");
    let _ = writeln!(output, "        ptype = cls._PAYLOAD.get(variant)");
    let _ = writeln!(output, "        if ptype is None:");
    let _ = writeln!(
        output,
        "            if payload is not None: raise AdapterError(\"unexpected_payload\")"
    );
    let _ = writeln!(output, "            return cls(variant)");
    let _ = writeln!(
        output,
        "        if payload is None: raise AdapterError(\"missing_payload\")"
    );
    let _ = writeln!(
        output,
        "        return cls(variant, ptype.try_from_value(payload))\n"
    );
    for variant in variants {
        let vname = variant.name().as_str();
        let vconst = format!(
            "VARIANT_{}_{}",
            name.to_ascii_uppercase(),
            vname.to_ascii_uppercase()
        );
        let _ = writeln!(output, "{name}._BY_NAME[\"{vname}\"] = {vconst}");
        let _ = writeln!(output, "{name}._BY_ORD[{vconst}] = \"{vname}\"");
        match variant.payload() {
            None => {
                let _ = writeln!(output, "{name}._PAYLOAD[\"{vname}\"] = None");
            }
            Some(payload) => {
                let payload_name = resolve_type_name(schema, payload);
                let _ = writeln!(output, "{name}._PAYLOAD[\"{vname}\"] = {payload_name}");
            }
        }
    }
    output.push('\n');
}

fn emit_vector(
    output: &mut String,
    schema: &Schema,
    name: &str,
    element: &TypeId,
    min_len: u32,
    max_len: u32,
) {
    let element_name = resolve_type_name(schema, *element);
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    MIN_LEN = {min_len}");
    let _ = writeln!(output, "    MAX_LEN = {max_len}");
    let _ = writeln!(
        output,
        "    def __init__(self, value): self.value = list(value)"
    );
    let _ = writeln!(output, "    def to_value(self):");
    let _ = writeln!(output, "        n = len(self.value)");
    let _ = writeln!(
        output,
        "        if not (self.MIN_LEN <= n <= self.MAX_LEN): raise AdapterError(\"length\")"
    );
    let _ = writeln!(
        output,
        "        return (\"vector\", [_child_value(x, {element_name}) for x in self.value])"
    );
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(output, "        {}", tagged_check("vector", 2));
    let _ = writeln!(output, "        items = v[1]");
    let _ = writeln!(output, "        {}", exact_type_check("items", "list"));
    let _ = writeln!(output, "        n = len(items)");
    let _ = writeln!(
        output,
        "        if not (cls.MIN_LEN <= n <= cls.MAX_LEN): raise AdapterError(\"length\")"
    );
    let _ = writeln!(
        output,
        "        return cls([{element_name}.try_from_value(x) for x in items])\n"
    );
}

fn emit_map(
    output: &mut String,
    schema: &Schema,
    name: &str,
    key: &TypeId,
    value: &TypeId,
    min_len: u32,
    max_len: u32,
) {
    let key_name = resolve_type_name(schema, *key);
    let value_name = resolve_type_name(schema, *value);
    let entry_name = format!("{name}Entry");
    let _ = writeln!(output, "class {entry_name}:");
    let _ = writeln!(
        output,
        "    def __init__(self, key, value): self.key = key; self.value = value"
    );
    let _ = writeln!(output, "    def to_entry(self):");
    let _ = writeln!(output, "        kv = _child_value(self.key, {key_name})");
    let _ = writeln!(
        output,
        "        return (encode(kv), kv, _child_value(self.value, {value_name}))\n"
    );
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    MIN_LEN = {min_len}");
    let _ = writeln!(output, "    MAX_LEN = {max_len}");
    let _ = writeln!(
        output,
        "    def __init__(self, value): self.value = list(value)"
    );
    let _ = writeln!(output, "    def to_value(self):");
    let _ = writeln!(output, "        n = len(self.value)");
    let _ = writeln!(
        output,
        "        if not (self.MIN_LEN <= n <= self.MAX_LEN): raise AdapterError(\"length\")"
    );
    let _ = writeln!(output, "        entries = []");
    let _ = writeln!(output, "        for e in self.value:");
    let _ = writeln!(output, "            {}", exact_type_check("e", &entry_name));
    let _ = writeln!(output, "            entries.append(e.to_entry())");
    let _ = writeln!(output, "        entries.sort(key=lambda t: t[0])");
    let _ = writeln!(output, "        previous = None");
    let _ = writeln!(output, "        for e in entries:");
    let _ = writeln!(
        output,
        "            if previous == e[0]: raise AdapterError(\"non_canonical_map\")"
    );
    let _ = writeln!(output, "            previous = e[0]");
    let _ = writeln!(output, "        return (\"map\", entries)");
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(output, "        {}", tagged_check("map", 2));
    let _ = writeln!(output, "        entries = v[1]");
    let _ = writeln!(output, "        {}", exact_type_check("entries", "list"));
    let _ = writeln!(output, "        n = len(entries)");
    let _ = writeln!(
        output,
        "        if not (cls.MIN_LEN <= n <= cls.MAX_LEN): raise AdapterError(\"length\")"
    );
    let _ = writeln!(output, "        values = []");
    let _ = writeln!(output, "        previous = None");
    let _ = writeln!(output, "        for e in entries:");
    let _ = writeln!(
        output,
        "            if not _is_tuple(e, 3): raise AdapterError(\"type_mismatch\")"
    );
    let _ = writeln!(
        output,
        "            values.append({entry_name}({key_name}.try_from_value(e[1]), {value_name}.try_from_value(e[2])))"
    );
    let _ = writeln!(output, "            {}", exact_type_check("e[0]", "bytes"));
    let _ = writeln!(
        output,
        "            if e[0] != encode(e[1]) or (previous is not None and previous >= e[0]): raise AdapterError(\"non_canonical_map\")"
    );
    let _ = writeln!(output, "            previous = e[0]");
    let _ = writeln!(output, "        return cls(values)\n");
}

fn emit_replay(output: &mut String) {
    output.push_str("def replay():\n");
    output.push_str("    failures = []\n");
    output.push_str("    for case in VECTORS:\n");
    output.push_str("        try:\n");
    output.push_str("            decode(case.bytes)\n");
    output.push_str("            decoded_ok = True; kind = None\n");
    output.push_str("        except DecodeError as exc:\n");
    output.push_str("            decoded_ok = False; kind = exc.kind\n");
    output.push_str(
        "        if case.expect_kind == \"accept\" or case.expect_kind == \"validate_reject\":\n",
    );
    output.push_str("            if not decoded_ok:\n");
    output.push_str("                failures.append((case.name, \"expected decode ok\", kind))\n");
    output.push_str("        elif case.expect_kind == \"decode_reject\":\n");
    output.push_str("            if decoded_ok or kind != case.expect_label:\n");
    output.push_str(
        "                failures.append((case.name, \"expected \" + case.expect_label, kind))\n",
    );
    output.push_str("    if failures:\n");
    output.push_str("        for name, expected, got in failures:\n");
    output.push_str("            print(\"vector \" + name + \" failed: expected \" + str(expected) + \" got \" + str(got))\n");
    output.push_str("        raise SystemExit(1)\n");
    output.push_str("    print(\"vectors replayed: \" + str(len(VECTORS)))\n\n");
    output.push_str("if __name__ == \"__main__\":\n");
    output.push_str("    replay()\n");
}

fn tuple_fields(items: &[TypeId]) -> String {
    let mut parts = Vec::new();
    for index in 0..items.len() {
        parts.push(format!("field_{index}"));
    }
    parts.join(", ")
}

fn tuple_to_value(schema: &Schema, items: &[TypeId]) -> String {
    let mut parts = Vec::new();
    for (index, item) in items.iter().enumerate() {
        let item_name = resolve_type_name(schema, *item);
        parts.push(format!("_child_value(self.field_{index}, {item_name})"));
    }
    parts.join(", ")
}

fn record_fields(fields: &[FieldDef]) -> Result<String, CodegenError> {
    let mut parts = Vec::new();
    for field in fields {
        parts.push(field.name().as_str().to_owned());
    }
    Ok(parts.join(", "))
}

fn resolve_type_name(schema: &Schema, id: TypeId) -> String {
    match schema.type_by_id(id) {
        Some(definition) => definition.name().as_str().to_owned(),
        None => "Unresolved".to_owned(),
    }
}

