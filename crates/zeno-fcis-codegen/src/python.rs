//! Typed Python domain adapter and ZCVE/1 replay rendering.
//!
//! Emits ordinary Python classes with strict `to_value`/`try_from_value`
//! conversions, a fixed ZCVE/1 encoder/decoder module used for replay, and the
//! vector evidence list. Stable numeric identifiers drive every emitted
//! reference.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use zeno_fcis_schema::{FieldDef, Schema, TypeDef, TypeId, TypeKind};

use crate::vectors::VectorCase;
use crate::{CodegenError, GenerationSpec};

/// Renders the fixed ZCVE/1 Python codec module (`zcve.py`).
pub(crate) fn render_codec_module() -> String {
    ZCVE_PY.to_owned()
}

/// Renders the typed Python adapter module (`<python_module>.py`).
pub(crate) fn render_adapter_module(
    schema: &Schema,
    spec: &GenerationSpec,
    cases: &[VectorCase],
) -> Result<String, CodegenError> {
    validate_python_names(schema, spec)?;
    let mut output = String::new();
    output.push_str("# @generated by zeno-fcis-codegen/1; do not edit.\n");
    let _ = writeln!(output, "from zcve import encode, decode, DecodeError\n");
    let _ = writeln!(output, "GENERATOR_ID = \"{}\"", crate::render::GENERATOR_ID);
    let _ = writeln!(output, "PYTHON_MODULE = \"{}\"", spec.python_module());
    let _ = writeln!(output, "PROFILE_NAME = \"{}\"", schema.profile().as_str());
    let _ = writeln!(output, "PROFILE_VERSION = {}", schema.version());
    let _ = writeln!(output, "ROOT_TYPE_ID = {}\n", schema.root_type().get());
    emit_constants(&mut output, schema);
    emit_adapter_error(&mut output);
    for definition in schema.types() {
        emit_type(&mut output, schema, definition)?;
    }
    output.push_str("class VectorCase:\n");
    output.push_str(
        "    def __init__(self, name, kind, bytes, expect_kind, expect_label, validate_type):\n",
    );
    output.push_str("        self.name = name; self.kind = kind; self.bytes = bytes\n");
    output.push_str("        self.expect_kind = expect_kind; self.expect_label = expect_label\n");
    output.push_str("        self.validate_type = validate_type\n\n");
    output.push_str(crate::vectors::render_python(cases).as_str());
    emit_replay(&mut output);
    Ok(output)
}

fn emit_constants(output: &mut String, schema: &Schema) {
    for definition in schema.types() {
        let type_name = definition.name().as_str().to_ascii_uppercase();
        let _ = writeln!(output, "TYPE_{type_name} = {}", definition.id().get());
        match definition.kind() {
            TypeKind::Record { fields } => {
                for field in fields.iter() {
                    let field_name = field.name().as_str().to_ascii_uppercase();
                    let _ = writeln!(
                        output,
                        "FIELD_{type_name}_{field_name} = {}",
                        field.id().get()
                    );
                }
            }
            TypeKind::Enum { .. } | TypeKind::Sum { .. } => {
                emit_variant_constants(output, definition, &type_name);
            }
            _ => {}
        }
    }
    output.push('\n');
}

fn emit_variant_constants(output: &mut String, definition: &TypeDef, type_name: &str) {
    let variants: Box<dyn Iterator<Item = (u16, &str)>> = match definition.kind() {
        TypeKind::Enum { variants } => {
            Box::new(variants.iter().map(|v| (v.id().get(), v.name().as_str())))
        }
        TypeKind::Sum { variants } => {
            Box::new(variants.iter().map(|v| (v.id().get(), v.name().as_str())))
        }
        _ => Box::new(core::iter::empty()),
    };
    for (id, name) in variants {
        let upper = name.to_ascii_uppercase();
        let _ = writeln!(output, "VARIANT_{type_name}_{upper} = {id}");
    }
}

fn emit_adapter_error(output: &mut String) {
    output.push_str("class AdapterError(Exception):\n");
    output.push_str("    def __init__(self, kind):\n");
    output.push_str("        super().__init__(kind)\n");
    output.push_str("        self.kind = kind\n\n");
    output.push_str("def _is_tuple(value, size):\n");
    output.push_str("    return type(value) is tuple and len(value) == size\n\n");
    output.push_str("def _is_tagged(value, tag, size):\n");
    output.push_str(
        "    return _is_tuple(value, size) and type(value[0]) is str and value[0] == tag\n\n",
    );
    output.push_str("def _child_value(child, expected):\n");
    output.push_str("    if type(child) is not expected: raise AdapterError(\"type_mismatch\")\n");
    output.push_str("    return child.to_value()\n\n");
}

/// Renders the incoming check that `v` is exactly a `size`-element value
/// tuple carrying `tag`; short, extra, and non-tuple values are rejected
/// before any element is indexed.
fn tagged_check(tag: &str, size: usize) -> String {
    format!("if not _is_tagged(v, \"{tag}\", {size}): raise AdapterError(\"type_mismatch\")")
}

fn emit_type(
    output: &mut String,
    schema: &Schema,
    definition: &TypeDef,
) -> Result<(), CodegenError> {
    let name = definition.name().as_str();
    match definition.kind() {
        TypeKind::Unit => emit_unit(output, name),
        TypeKind::Bool => emit_bool(output, name),
        TypeKind::U128 { min, max } => emit_u128(output, name, *min, *max),
        TypeKind::I128 { min, max } => emit_i128(output, name, *min, *max),
        TypeKind::Bytes { min_len, max_len } => emit_bytes(output, name, *min_len, *max_len),
        TypeKind::Text { min_len, max_len } => emit_text(output, name, *min_len, *max_len),
        TypeKind::Enum { variants } => emit_enum(output, definition, name, variants),
        TypeKind::Tuple { items } => emit_tuple(output, schema, definition, name, items),
        TypeKind::Record { fields } => emit_record(output, schema, definition, name, fields)?,
        TypeKind::Sum { variants } => emit_sum(output, schema, definition, name, variants),
        TypeKind::Vector {
            element,
            min_len,
            max_len,
        } => emit_vector(output, schema, name, element, *min_len, *max_len),
        TypeKind::Map {
            key,
            value,
            min_len,
            max_len,
        } => emit_map(output, schema, name, key, value, *min_len, *max_len),
    }
    Ok(())
}

fn emit_unit(output: &mut String, name: &str) {
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    def to_value(self): return (\"unit\",)");
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(output, "        {}", tagged_check("unit", 1));
    let _ = writeln!(output, "        return cls()\n");
}

fn emit_bool(output: &mut String, name: &str) {
    let _ = writeln!(output, "class {name}:");
    let _ = writeln!(output, "    def __init__(self, value): self.value = value");
    let _ = writeln!(output, "    def to_value(self):");
    let _ = writeln!(output, "        {}", exact_type_check("self.value", "bool"));
    let _ = writeln!(output, "        return (\"bool\", self.value)");
    let _ = writeln!(output, "    @classmethod");
    let _ = writeln!(output, "    def try_from_value(cls, v):");
    let _ = writeln!(output, "        {}", tagged_check("bool", 2));
    let _ = writeln!(output, "        {}", exact_type_check("v[1]", "bool"));
    let _ = writeln!(output, "        return cls(v[1])\n");
}

/// Renders a Python statement rejecting anything but the exact built-in type.
///
/// `type(x) is T` deliberately excludes subclasses: `bool` is an `int`
/// subclass, and subclasses can override comparison or `encode` to bypass the
/// range, length, and ASCII checks that follow.
fn exact_type_check(expression: &str, python_type: &str) -> String {
    format!("if type({expression}) is not {python_type}: raise AdapterError(\"type_mismatch\")")
}

/// Emits the outgoing enum/sum check that `self.variant` is a generated
/// variant name (a plain `str` key of `_BY_NAME`).
fn emit_variant_name_check(output: &mut String) {
    let _ = writeln!(
        output,
        "        {}",
        exact_type_check("self.variant", "str")
    );
    let _ = writeln!(
        output,
        "        if self.variant not in self._BY_NAME: raise AdapterError(\"unknown_variant\")"
    );
}

