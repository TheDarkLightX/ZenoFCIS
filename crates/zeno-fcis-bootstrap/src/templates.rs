    output.push_str("/// Exact generated project bindings with no caller-supplied catalog.\n");
    output.push_str("#[derive(Clone, Debug, Eq, PartialEq)]\n");
    output.push_str("pub struct GeneratedProject { catalog: ProjectCatalog }\n\n");
    output.push_str("impl GeneratedProject {\n");
    output.push_str("    /// Reconstructs and revalidates the exact generation-time catalog.\n");
    output.push_str(
        "    pub fn try_new<H: CommitmentHasher>() -> Result<Self, GeneratedProjectError> {\n",
    );
    output.push_str("        if H::ALGORITHM_ID != HASH_ALGORITHM_ID {\n");
    output.push_str("            return Err(GeneratedProjectError::HashAlgorithmMismatch);\n");
    output.push_str("        }\n");
