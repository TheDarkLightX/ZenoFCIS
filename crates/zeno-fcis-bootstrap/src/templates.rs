    output.push_str("        &self,\n");
    writeln!(output, "        root: &crate::generated::{root_type},")
        .map_err(|_| BootstrapError::Render)?;
    output.push_str("        limits: ValidationLimits,\n");
    output.push_str("    ) -> Result<SchemaAdmittedEnvelope, GeneratedProjectError> {\n");
