#!/usr/bin/env python3
"""Requalify the existing human-authored Cranelift udiv/urem pilot against a
newer, exact upstream commit. No merge, upstream write, or new synthesis claim.

Executable evidence is produced ONLY after rebuilding pristine and patched
Wasmtime at this pin and executing the same WebAssembly A/B oracle. This file
does not reinterpret historical receipts as newly executed measurements.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

import post_souper_portability_28 as prior

NEW_UPSTREAM = "e355dc640d047ab76dbf4402567d0c124bfdecd6"
OLD_UPSTREAM = "8b19f199f89da864c529b3fa3ca2f7e40d5de609"
NEW_BLOBS = {
    "cranelift/codegen/src/context.rs": "472f3d9db48aad0742e056861ee42243d76e50f4",
    "cranelift/codegen/meta/src/shared/instructions.rs": "1fcac42ebfb4b5a7c9220cd71ddd7688776cd05d",
    "cranelift/codegen/src/isa/x64/lower.isle": "42e981a5f41dc734c2a487c920b02abb2108b6f8",
    "cranelift/interpreter/src/step.rs": "0ed9ade45cd631793d6b660a2121fd54c46ddbb4",
}
OLD_X64_BLOB = "654189182a09c1e22478faa157cd421ff8ed8894"
SOURCE_ANCHOR = "(x64_div ty a (imm $I64 0) (put_in_gpr b) (TrapCode.INTEGER_DIVISION_BY_ZERO))"
RECEIPT_SCHEMA = "zenofcis/tier1-upstream-requalification/1"


def configure() -> None:
    # Isolate old pin as historical: overwrite only imported Python module
    # variables in this process, never change a checked-in experiment file.
    prior.UPSTREAM = NEW_UPSTREAM
    prior.BLOBS = dict(NEW_BLOBS)
    prior.PR = "source-pinned requalification at " + NEW_UPSTREAM
    prior.configure()


def preflight(upstream: Path) -> dict:
    configure()
    prior.preflight(upstream)
    lower = (upstream / "cranelift/codegen/src/isa/x64/lower.isle").read_text()
    # These are distinct scalar lowering rules. Reuse of x64_div with the
    # explicit zero high part and divide-by-zero trap must be unchanged.
    if lower.count(SOURCE_ANCHOR) != 2:
        raise ValueError("scalar Udiv/Urem x64_div lowering anchors drifted")
    if lower.count("(rule 1 (lower (udiv _ a @ (value_type (fits_in_64 ty)) b))") != 1:
        raise ValueError("unsigned quotient lowering shape drifted")
    if lower.count("(rule 1 (lower (urem _ a @ (value_type (fits_in_64 ty)) b))") != 1:
        raise ValueError("unsigned remainder lowering shape drifted")
    if NEW_BLOBS["cranelift/codegen/src/isa/x64/lower.isle"] == OLD_X64_BLOB:
        raise ValueError("expected explicitly changed upstream x64 source blob")
    return {
        "schema": RECEIPT_SCHEMA,
        "new_upstream": NEW_UPSTREAM,
        "previous_upstream": OLD_UPSTREAM,
        "new_blobs": NEW_BLOBS,
        "old_x64_blob": OLD_X64_BLOB,
        "unchanged_other_three_blobs": all(
            v == prior_expected
            for k, v, prior_expected in [
                ("context", NEW_BLOBS["cranelift/codegen/src/context.rs"],
                 "472f3d9db48aad0742e056861ee42243d76e50f4"),
                ("meta", NEW_BLOBS["cranelift/codegen/meta/src/shared/instructions.rs"],
                 "1fcac42ebfb4b5a7c9220cd71ddd7688776cd05d"),
                ("interpreter", NEW_BLOBS["cranelift/interpreter/src/step.rs"],
                 "0ed9ade45cd631793d6b660a2121fd54c46ddbb4"),
            ]),
        "division_anchor_count": lower.count(SOURCE_ANCHOR),
        "classification": "static pinned source and exact div lowering anchors, NOT a new compiler execution",
        "evidence_limits": [
            "Successful source preflight does not prove optimizer correctness, rule compatibility or performance",
            "All native code costs must be regenerated by real A/B compilation and audited",
            "Only x86-64 unsigned i64 adjacent udiv/urem is admitted; flags, poison and general ISA refinement remain unproved",
        ],
    }


def self_test() -> None:
    configure()
    prior.self_test()
    assert len(NEW_UPSTREAM) == 40
    assert OLD_UPSTREAM != NEW_UPSTREAM and OLD_X64_BLOB != NEW_BLOBS["cranelift/codegen/src/isa/x64/lower.isle"]
    assert prior.UPSTREAM == NEW_UPSTREAM
    assert prior.BLOBS == NEW_BLOBS
    print("Pinned upstream adapter, installer negative controls and branch isolation passed")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--mode", choices=("self-test", "preflight", "install", "qualify", "audit"), required=True)
    p.add_argument("--upstream", type=Path)
    p.add_argument("--out", type=Path)
    a = p.parse_args()
    if a.mode == "self-test":
        self_test()
        return
    if a.mode in ("preflight", "install", "audit") and a.upstream is None:
        p.error("--upstream required")
    if a.mode in ("install", "qualify", "audit") and a.out is None:
        p.error("--out required")
    if a.mode == "preflight":
        print(json.dumps(preflight(a.upstream), indent=2, sort_keys=True))
    elif a.mode == "install":
        if (a.out / "upstream-requalification-preflight.json").exists():
            raise ValueError("will not overwrite earlier requalification preflight")
        a.out.mkdir(parents=True, exist_ok=True)
        check = preflight(a.upstream)
        (a.out / "upstream-requalification-preflight.json").write_text(
            json.dumps(check, indent=2, sort_keys=True) + "\n")
        prior.install(a.upstream, a.out / "install.json")
        modified = set(subprocess.check_output(
            ["git", "-C", str(a.upstream), "diff", "--name-only"], text=True).splitlines())
        if modified != set(NEW_BLOBS):
            raise AssertionError("unexpected modified upstream paths")
    elif a.mode == "qualify":
        configure()
        prior.qualify(a.out)
    else:
        configure()
        preflight_doc = json.loads((a.out / "upstream-requalification-preflight.json").read_text())
        if preflight_doc["new_blobs"] != NEW_BLOBS or preflight_doc["new_upstream"] != NEW_UPSTREAM:
            raise ValueError("source pins drifted")
        prior.audit(a.out, a.upstream)
        report = json.loads((a.out / "post_souper_cost_audit.json").read_text())
        if report["upstream_source_commit"] != NEW_UPSTREAM or not report["contexts"]:
            raise ValueError("A/B audit missing current pin or contexts")
        result = {
            "schema": RECEIPT_SCHEMA,
            "classification": "new pinned Wasmtime executable A/B finite checks and native emitted-code costs",
            "upstream": NEW_UPSTREAM,
            "experiment_source_commit": subprocess.check_output(
                ["git", "rev-parse", "HEAD"], text=True).strip(),
            "context_count": len(report["contexts"]),
            "costs": {n: {
                "native_instruction_bytes_saved": c["baseline_minus_experimental_decoded_bytes"],
                "native_div_instructions_removed": c["baseline_minus_experimental_divs"],
                "whole_aot_bytes_saved": c["baseline_minus_experimental_aot_bytes"],
            } for n, c in sorted(report["contexts"].items())},
            "source_guard_sha256": hashlib.sha256(
                (a.out / "upstream-requalification-preflight.json").read_bytes()).hexdigest(),
            "native_audit_sha256": hashlib.sha256(
                (a.out / "post_souper_cost_audit.json").read_bytes()).hexdigest(),
            "verification_classes": [
                "finite guest execution + expected traps",
                "AOT and disassembly SHA-256 replay",
                "native x86-64 decoded instruction byte and DIV count",
            ],
            "limitations": [
                "A single pinned host/source experiment; no proof of all machine states or representative profitability",
                "Compilation is not a newly synthesized candidate; previously human-authored forward-pair fusion",
                "Decoded x86 native instruction bytes are not CLIF costs, whole-AOT size or throughput",
                "No independent VeriISLE proof for the patched multi-result lowering",
            ],
        }
        receipt = a.out / "upstream-requalification-audit.json"
        if receipt.exists():
            raise ValueError("will not overwrite prior requalification audit")
        receipt.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
        print(json.dumps({"upstream": NEW_UPSTREAM, "contexts": len(report["contexts"]),
                          "native_byte_deltas": {n: row["native_instruction_bytes_saved"]
                                                for n, row in result["costs"].items()}}, sort_keys=True))


if __name__ == "__main__":
    main()
