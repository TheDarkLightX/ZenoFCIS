#!/usr/bin/env python3
"""Regenerate a template contract and its schema provenance with the native producer.

The scratch compilation intentionally has no old schema-origin bridge: this is
an explicit schema revision. The producer's freshly emitted framing supplies
its commitment; a second normal generation verifies that origin binding.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def refresh_site_law_fixture(contract):
    """Refresh the demo reporter's expected scopes from the generated declaration.

    This fixture checks reporting. Independent project-law completeness and the
    counterpolicy refusal tests remain separate checks of the actual obligations.
    """
    fixture = ROOT / 'site/tests/templates' / (contract.name + '.mjs')
    if not fixture.exists():
        return
    declaration = (contract / 'src/v2_contract.rs').read_text()
    rows = re.findall(r'l::Law \{\s+id: (\d+),\s+kind: l::Kind::(\w+),\s+scope: l::Scope::(\w+),', declaration)
    assert rows, 'missing generated law declarations'
    accepts = {'Accept': {'Always', 'Committing', 'Accept'},
               'CommittedFailure': {'Always', 'Committing', 'CommittedFailure'},
               'Reject': {'Always', 'Reject'}}
    expected = {kind: [int(i) for i, law_kind, scope in rows
                       if law_kind != 'InitialCondition' and scope in scopes]
                for kind, scopes in accepts.items()}
    replacement = 'export const laws = ' + json.dumps(expected) + ';'
    text, count = re.subn(r'export const laws = \{.*?\};', replacement,
                          fixture.read_text(), count=1, flags=re.S)
    assert count == 1, 'missing demo law fixture'
    fixture.write_text(text)


def refresh(cli, contract, oracle=False):
    def run(*args):
        subprocess.run(['nice', '-n', '19', 'ionice', '-c3', str(cli), '--no-kb', *map(str, args)], check=True)
    with tempfile.TemporaryDirectory(prefix='template-rules-', dir=os.environ.get('TMPDIR')) as tmp:
        staged = Path(tmp)
        (staged / 'v2').mkdir()
        for name in ('project.zeno', 'v2/policy.json'):
            shutil.copyfile(contract / name, staged / name)
        run('generate', 'contract', staged)
        generated = (staged / 'src/v2_contract.rs').read_text()
        framing = generated[generated.index('pub const FRAMING:'):]
        values = re.search(r'schema:\s*\[([^]]+)\]', framing).group(1)
        commitment = bytes(int(n.strip(), 0) for n in values.split(',') if n.strip()).hex()
        schema = (staged / 'v2/schema.zcve').read_bytes()
        for name in ('src/v2_contract.rs', 'v2/schema.zcve', 'v2/policy.zcve'):
            (contract / name).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(staged / name, contract / name)
        origin = contract / 'v2/schema-origin.json'
        if origin.exists():
            record = {'schema': 'zeno-fcis/template-schema-origin/1',
                      'retained_original': str((contract / 'v2/schema.zcve').relative_to(ROOT)),
                      'sha256': hashlib.sha256(schema).hexdigest(), 'bytes': len(schema),
                      'schema_commitment': commitment,
                      'source_inputs': {name: hashlib.sha256((contract / name).read_bytes()).hexdigest()
                                        for name in ('project.zeno', 'build.rs', 'profile.rs')},
                      'qualification': 'Regenerated by tools/refresh_template_rules.py using generate contract; the build independently checks lower_schema output.'}
            origin.write_text(json.dumps(record, indent=2) + '\n')
        run('generate', 'contract', contract, '--check')
        if oracle:
            retained = ROOT / 'verification/kernel-laws/src/oracle/templates' / contract.name
            (retained / 'v2').mkdir(parents=True, exist_ok=True)
            (retained / 'src').mkdir(parents=True, exist_ok=True)
            # Keep original/ and its legacy schema/bindings pinned. Only the
            # current checked declaration copy follows this template revision.
            for name in ('project.zeno', 'v2/policy.json', 'v2/schema-origin.json', 'v2/run-properties.json'):
                if (contract / name).exists():
                    shutil.copyfile(contract / name, retained / name)
            run('generate', 'contract', contract, '--out', retained)
            run('generate', 'contract', retained, '--check')
        refresh_site_law_fixture(contract)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cli', type=Path, required=True)
    parser.add_argument('contract', type=Path)
    parser.add_argument('--oracle', action='store_true')
    args = parser.parse_args()
    refresh(args.cli.resolve(), args.contract.resolve(), args.oracle)
