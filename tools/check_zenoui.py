#!/usr/bin/env python3
"""Build three checked UIs and independently reproduce their emitted bytes."""
import argparse
import json
import os
from pathlib import Path
from zenoui import ROOT, hashes, run, save

PROJECTS = {
    "withdrawal-queue": ROOT / "crates/zeno-fcis-cli/templates/withdrawal-queue",
    "inventory-reservation": ROOT / "crates/zeno-fcis-cli/templates/inventory-reservation",
    "wide-counter": ROOT / "site/zenoui/test-projects/wide-counter",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--oracle", type=Path, default=Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target")) / "release/ui_contract")
    parser.add_argument("--runtime", type=Path, default=ROOT / "site/public/factory.wasm")
    args = parser.parse_args()
    report = {"format":"zenoui/laws/1", "apps":{}}
    run(["node", ROOT / "site/tests/zenoui-contract.test.mjs"])
    run(["python3", ROOT / "tools/test_zenoui_text.py"])
    run(["node", ROOT / "site/tests/zenoui-integer-input.test.mjs"])
    run(["node", ROOT / "site/tests/zenoui-decimal-rules.test.mjs"])
    run(["node", ROOT / "site/tests/zenoui-label-text.test.mjs"])
    run(["node", ROOT / "site/tests/zenoui-durable-dispatch.test.mjs"])
    for name, project in PROJECTS.items():
        out = args.out.resolve() / name
        run(["python3", ROOT / "tools/zenoui.py", project, "--out", out / "app",
             "--evidence", out, "--oracle", args.oracle.resolve(), "--runtime", args.runtime.resolve()])
        # This second emission is a byte reproducibility specimen, not a checked app output.
        run(["node", ROOT / "site/zenoui/generate.mjs", out / "raw.json", out / "metadata.json",
             out / "repeated", args.runtime.resolve()])
        if hashes(out / "app") != hashes(out / "repeated"):
            raise ValueError(f"UiNondeterministicGeneration:{name}")
        report["apps"].update(json.loads((out / "laws.json").read_text())["apps"])
    save(args.out.resolve() / "laws.json", report)
    print("ZenoUI: three checked apps; identical regenerated bytes; all law controls and mounted native/Wasm journeys passed", flush=True)


if __name__ == "__main__":
    from telemetry import run_cli
    def _entrypoint():
        main()
    run_cli(_entrypoint)
