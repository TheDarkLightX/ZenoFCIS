#!/usr/bin/env python3
"""Regenerate the order migration fixture from the current template's rules.

The transformation changes the state and payment-action encodings. The CLI then checks the
whole migration simulation; no generated contract bytes are patched.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'crates/zeno-fcis-cli/templates/order-fulfillment'
TARGET = ROOT / 'crates/zeno-fcis-cli/tests/fixtures/order-fulfillment-split'
STATUS = {160: (False, 0), 161: (False, 1), 162: (True, 0),
          163: (True, 1), 164: (True, 2), 165: (False, 2), 166: (True, 3)}


def status(root):
    paid, progress = f'{root}.100.122', f'{root}.100.123'
    return f'choose({paid}, choose({progress} == 0, 162, choose({progress} == 1, 163, choose({progress} == 2, 164, 166))), choose({progress} == 0, 160, choose({progress} == 1, 161, 165)))'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cli', required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    (out / 'v2').mkdir()
    project = (SOURCE / 'project.zeno').read_text()
    project = project.replace('field 120 100 status 105;', 'type 113 bool PaidFlag;\ntype 114 int Progress in 0..=3;\nfield 122 100 paid 113;\nfield 123 100 progress 114;')
    def comparison(match):
        root, code = match.groups()
        paid, progress = STATUS[int(code)]
        return f'({root}.100.122 == {int(paid)} && {root}.100.123 == {progress})'
    project = re.sub(r'(pre|post)\.100\.120 == (16[0-6])', comparison, project)
    assert 'pre.100.120' not in project and 'post.100.120' not in project
    project = project.replace('field 141 104 request_action 108;', 'type 115 int RequestKind in 0..=3;\nfield 142 104 request_kind 115;')
    assert 'field 142 104' in project
    project = re.sub(r'outbox\.104\.141 == (17[5-8])', lambda m: f'outbox.104.142 == {int(m[1]) - 175}', project)
    rules = json.loads((SOURCE / 'v2/policy.json').read_text())
    rules['variables']['status'] = status('pre')
    rules['leaf_bindings']['113'] = ['Bool']
    for case in rules['cases']:
        for delivery in case['outbox']:
            if delivery['channel'] == 300:
                delivery['payload']['142'] = delivery['payload'].pop('141') - 175
    for law in rules.get('delivery_laws', {}).values():
        observations = law.get('observations', {})
        if 'outbox.104.141' in observations:
            observations['outbox.104.142'] = observations.pop('outbox.104.141')
            observations['outbox.104.142']['field'] = 142
    for fields in [rules['genesis'], *[c['post'] for c in rules['cases'] if c['post']]]:
        paid, progress = STATUS[fields.pop('120')]
        fields.update({'122': paid, '123': progress})
    mapping = {'schema': 'zeno-fcis/migration/2', 'state': {
        '121': {'from': 121},
        '122': {'expr': 'old.120 == 162 || old.120 == 163 || old.120 == 164 || old.120 == 166'},
        '123': {'expr': 'choose(old.120 == 166, 3, choose(old.120 == 160 || old.120 == 162, 0, choose(old.120 == 161 || old.120 == 163, 1, 2)))'}}}
    mapping['payloads'] = {'300': {'140': {'from': 140},
        '142': {'from': 141, 'map': {str(code): code - 175 for code in range(175, 179)}}}}
    (out / 'project.zeno').write_text(project)
    for name, value in [('v2/policy.json', rules), ('migration.json', mapping)]:
        (out / name).write_text(json.dumps(value, indent=2) + '\n')
    source = SOURCE / 'tests/decision-examples.txt'
    labels = []
    for line in source.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        before, after, deliveries = [p.strip().split() for p in line.split('|')]
        paid, progress = STATUS[int(before[0])]
        before = [before[1], str(int(paid)), str(progress), *before[2:]]
        paid, progress = STATUS[int(after[2])]
        after = [*after[:2], after[3], str(int(paid)), str(progress)]
        if deliveries[0] == '300':
            deliveries[2] = str(int(deliveries[2]) - 175)
        labels.append(' | '.join([' '.join(before), ' '.join(after), ' '.join(deliveries)]))
    (out / 'tests').mkdir()
    (out / 'tests/decision-examples.txt').write_text('# Generated by tools/refresh_order_split_fixture.py; source SHA-256 ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n' + '\n'.join(labels) + '\n')
    cli = str(Path(args.cli).resolve())
    subprocess.run([cli, '--no-kb', 'generate', 'contract', str(out)], check=True)
    # Do not retain obsolete schema-origin assertions or generated old layouts.
    for path in sorted(TARGET.rglob('*'), reverse=True):
        if path.is_file() and path.name != 'README.md':
            path.unlink()
    for path in out.rglob('*'):
        if path.is_file():
            target = TARGET / path.relative_to(out)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
    print(json.dumps({'status': 'generated', 'labels': len(labels), 'states': len(STATUS)}))


if __name__ == '__main__':
    main()
