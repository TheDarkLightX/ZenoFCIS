#!/usr/bin/env python3
"""Generate release-binary dependency notices from the locked, offline Cargo graph."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
# The two binary hosts in release-candidate.yml; default features match rc_package.
RELEASE_TARGETS = ("x86_64-unknown-linux-gnu", "aarch64-apple-darwin")
LICENSE_NAME = re.compile(r"^(?:licen[cs]es?|copying|copyright|notice|unlicense)(?:$|[._-])", re.I)
HEADER = """ZenoFCIS third-party notices

Generated by tools/third_party_notices.py. Do not edit by hand.
Inclusion: the union of normal dependency trees for the binaries declared in
release/package-set.toml, with default release features, on
x86_64-unknown-linux-gnu and aarch64-apple-darwin. Dev dependencies, build
dependencies and procedural-macro subtrees are excluded; ordinary runtime
dependencies such as proc-macro2 remain included when reached normally.
This is a dependency-level inventory, without linker dead-code analysis.
Licence expressions are copied verbatim from Cargo metadata; legacy '/' means OR.
Full texts below are the package's top-level licence/attribution files, files
under licence directories, and any declared license-file in the local registry.

"""


def cargo(root: Path, *arguments: str) -> str:
    return subprocess.check_output(
        ["cargo", "+1.97.1", *arguments, "--offline", "--locked", "--color", "never"],
        cwd=root, text=True,
    )


def selected_packages(root: Path = ROOT) -> list[dict]:
    metadata = json.loads(cargo(root, "metadata", "--format-version", "1"))
    by_name: dict[tuple[str, str], list[dict]] = {}
    for package in metadata["packages"]:
        by_name.setdefault((package["name"], package["version"]), []).append(package)
    configured = tomllib.loads((root / "release/package-set.toml").read_text())
    selected = {}
    for binary in configured["binaries"]:
        for target in RELEASE_TARGETS:
            tree = cargo(root, "tree", "-p", binary["package"], "--target", target,
                         "--edges", "normal,no-proc-macro", "--prefix", "none", "--format", "{p}")
            for row in tree.splitlines():
                match = re.fullmatch(r"(\S+) v(\S+)(?: \([^\n]*\))?(?: \(\*\))?", row)
                if not match:
                    raise ValueError("unrecognized Cargo dependency tree row")
                choices = by_name.get(match.groups(), [])
                if len(choices) != 1:
                    raise ValueError("dependency tree package is absent or ambiguous in metadata")
                package = choices[0]
                if package["id"] in metadata["workspace_members"]:
                    continue
                if not str(package["source"]).startswith("registry+"):
                    raise ValueError("third-party dependency is not from the local registry")
                selected[package["id"]] = package
    return sorted(selected.values(), key=lambda p: (p["name"], p["version"], p["source"]))


def license_files(package: dict) -> list[tuple[str, str]]:
    directory = Path(package["manifest_path"]).parent.resolve()
    paths = set()
    for path in directory.iterdir():
        if LICENSE_NAME.match(path.name):
            if path.is_dir():
                paths.update(p for p in path.rglob("*") if p.is_file())
            else:
                paths.add(path)
    if package.get("license_file"):
        paths.add(directory / package["license_file"])
    texts = []
    for path in sorted(paths, key=lambda p: p.relative_to(directory).as_posix()):
        if not path.resolve().is_relative_to(directory) or not path.is_file() or path.is_symlink():
            raise ValueError(f"{package['name']}: unsafe or missing licence file")
        content = path.read_bytes().decode("utf-8")
        if not content.strip():
            raise ValueError(f"{package['name']}: empty licence file")
        texts.append((path.relative_to(directory).as_posix(), content))
    if not texts:
        raise ValueError(f"{package['name']}: no local licence text")
    return texts


def generate(root: Path = ROOT) -> str:
    packages = selected_packages(root)
    if not packages:
        raise ValueError("release dependency inventory is empty")
    parts = [HEADER, f"Third-party packages: {len(packages)}\n\n"]
    for index, package in enumerate(packages):
        if not package.get("license"):
            raise ValueError(f"{package['name']}: missing licence expression")
        if index:
            parts.append("\n")
        parts.append(f"{'=' * 72}\nPackage: {package['name']} {package['version']}\n"
                     f"License: {package['license']}\n")
        for name, content in license_files(package):
            parts.extend([f"\n--- {name} ---\n", content, "" if content.endswith("\n") else "\n"])
    return "".join(parts)


def check_notices(path: Path, expected: str) -> None:
    if path.read_bytes() != expected.encode("utf-8"):
        raise AssertionError("THIRD_PARTY_NOTICES differs from the locked release dependency inventory")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="assert the committed notices are current")
    options = parser.parse_args()
    expected = generate()
    path = ROOT / "THIRD_PARTY_NOTICES"
    if options.check:
        check_notices(path, expected)
        print("third-party-notices: PASS (locked runtime graph and full local licence texts)")
    else:
        path.write_bytes(expected.encode("utf-8"))
        print("third-party-notices: wrote THIRD_PARTY_NOTICES")


if __name__ == "__main__":
    main()
