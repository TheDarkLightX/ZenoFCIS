def cargo_lock_checksums() -> dict[tuple[str, str, str], str]:
    document = load_toml(LOCK_PATH)
    packages = document.get("package")
    if not isinstance(packages, list):
        raise RcError("Cargo.lock has no package set")
    checksums: dict[tuple[str, str, str], str] = {}
    for package in packages:
        if not isinstance(package, dict):
            continue
        name = package.get("name")
        version = package.get("version")
        source = package.get("source")
        checksum = package.get("checksum")
        if all(isinstance(item, str) for item in (name, version, source, checksum)):
            checksums[(str(name), str(version), str(source))] = str(checksum)
    return checksums


def bom_ref(package: dict[str, object]) -> str:
    name = quote(str(package["name"]), safe="-._~")
    version = quote(str(package["version"]), safe="-._~")
    source = package.get("source")
    base = f"pkg:cargo/{name}@{version}"
    if isinstance(source, str):
        return f"{base}?repository_url={quote(source, safe='')}"
    return base


def build_sbom(
    metadata: dict[str, object], commit: str, version: str
) -> dict[str, object]:
    packages = metadata.get("packages")
    resolve = metadata.get("resolve")
    if not isinstance(packages, list) or not isinstance(resolve, dict):
        raise RcError("complete Cargo metadata omits packages or resolution")
    checksums = cargo_lock_checksums()
    by_id = {
        str(package["id"]): package
        for package in packages
        if isinstance(package, dict) and "id" in package
    }
    components = []
    for package in sorted(
        by_id.values(),
        key=lambda item: (
            str(item["name"]),
            str(item["version"]),
            str(item.get("source")),
        ),
    ):
        component: dict[str, object] = {
            "type": "library",
            "bom-ref": bom_ref(package),
            "name": package["name"],
            "version": package["version"],
            "purl": bom_ref(package),
        }
        license_value = package.get("license")
        if isinstance(license_value, str) and license_value:
            component["licenses"] = [{"expression": license_value}]
        source = package.get("source")
        if isinstance(source, str):
            checksum = checksums.get(
                (str(package["name"]), str(package["version"]), source)
            )
            if checksum is not None:
                component["hashes"] = [{"alg": "SHA-256", "content": checksum}]
        if package.get("id") in metadata.get("workspace_members", []):
            component["properties"] = [{"name": "zeno-fcis:workspace", "value": "true"}]
        components.append(component)

    nodes = resolve.get("nodes")
    if not isinstance(nodes, list):
        raise RcError("Cargo resolution nodes are malformed")
    dependencies = []
    for node in nodes:
        if not isinstance(node, dict) or node.get("id") not in by_id:
            continue
        dependency_ids = node.get("dependencies")
        if not isinstance(dependency_ids, list):
            raise RcError("Cargo resolution dependency list is malformed")
        dependencies.append(
            {
                "ref": bom_ref(by_id[str(node["id"])]),
                "dependsOn": sorted(
                    bom_ref(by_id[str(dependency)])
                    for dependency in dependency_ids
                    if str(dependency) in by_id
                ),
            }
        )

    timestamp = git_text("show", "-s", "--format=%cI", commit)
    serial = uuid.uuid5(
        uuid.NAMESPACE_URL, f"https://github.com/TheDarkLightX/ZenoFCIS@{commit}"
    )
    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.6",
        "serialNumber": f"urn:uuid:{serial}",
        "version": 1,
        "metadata": {
            "timestamp": timestamp,
            "component": {
                "type": "library",
                "bom-ref": f"pkg:cargo/zeno-fcis@{version}",
                "name": "zeno-fcis",
                "version": version,
                "purl": f"pkg:cargo/zeno-fcis@{version}",
            },
            "properties": [
                {"name": "zeno-fcis:source-commit", "value": commit},
                {"name": "zeno-fcis:rust-toolchain", "value": "1.97.1"},
            ],
        },
        "components": components,
        "dependencies": sorted(dependencies, key=lambda item: str(item["ref"])),
    }


def artifact_entries(output: Path, excluded: set[Path]) -> list[dict[str, object]]:
    entries = []
    for path in sorted(item for item in output.rglob("*") if item.is_file()):
        if path in excluded:
            continue
        entries.append(
            {
                "path": path.relative_to(output).as_posix(),
                "sha256": sha256(path),
                "size": path.stat().st_size,
            }
        )
    return entries


def deterministic_bundle(output: Path, destination: Path) -> None:
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_STORED) as archive:
        for path in sorted(item for item in output.rglob("*") if item.is_file()):
            if path == destination:
                continue
            info = zipfile.ZipInfo(path.relative_to(output).as_posix(), FIXED_ZIP_TIME)
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            archive.writestr(info, path.read_bytes())


def extract_checked_crate(archive_path: Path, destination: Path) -> None:
    with tarfile.open(archive_path, mode="r:gz") as archive:
        members = archive.getmembers()
        seen: set[PurePosixPath] = set()
        for member in members:
            relative = PurePosixPath(member.name)
            if (
                relative.is_absolute()
                or not relative.parts
                or relative.parts[0] != archive_path.stem
                or relative in seen
                or ".." in relative.parts
                or member.issym()
                or member.islnk()
                or not (member.isdir() or member.isfile())
            ):
                raise RcError(
                    f"crate archive contains an unsafe member: {archive_path.name}:{member.name}"
                )
            seen.add(relative)
        archive.extractall(destination, members=members, filter="data")


def compiler_environment(environment: dict[str, str]) -> dict[str, str]:
    """Exclude inherited flag, compiler, wrapper, and target overrides."""
    overrides = {
        "RUSTFLAGS", "RUSTDOCFLAGS", "CARGO_ENCODED_RUSTFLAGS", "CARGO_ENCODED_RUSTDOCFLAGS",
        "RUSTC", "RUSTDOC", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER",
        "CARGO_BUILD_RUSTC", "CARGO_BUILD_RUSTDOC", "CARGO_BUILD_RUSTC_WRAPPER",
        "CARGO_BUILD_RUSTC_WORKSPACE_WRAPPER", "CARGO_BUILD_TARGET",
    }
    return {name: value for name, value in environment.items() if name not in overrides}


def remapped_compiler_environment(
    environment: dict[str, str], source: Path, destination: str,
) -> dict[str, str]:
    """Remap source and dependency home paths without inherited flag overrides."""
    result = compiler_environment(environment)
    # Rust uses the last matching remap. Keep the specific source mapping last
    # when a normal checkout is itself under the home directory.
    remaps = [f"--remap-path-prefix={Path.home()}=/zeno-fcis-home",
              f"--remap-path-prefix={source}={destination}"]
    if any("\x1f" in remap or "\0" in remap for remap in remaps):
        raise RcError("staging path cannot be encoded as one compiler argument")
    result["CARGO_ENCODED_RUSTFLAGS"] = "\x1f".join(remaps)
    result["CARGO_ENCODED_RUSTDOCFLAGS"] = "\x1f".join(["-D", "warnings", *remaps])
    return result


def compiler_flag_evidence(environment: dict[str, str], source: Path, label: str) -> dict[str, list[str]]:
    return {key: [flag.replace(str(source), label).replace(str(Path.home()), "<home>")
                  for flag in environment[key].split("\x1f")]
            for key in ("CARGO_ENCODED_RUSTFLAGS", "CARGO_ENCODED_RUSTDOCFLAGS")}


PACKAGED_TEST_INPUTS_PATH = ROOT / "release" / "packaged-test-inputs.json"
PACKAGED_TEST_INPUTS_FORMAT = "zeno-fcis/packaged-test-inputs/1"
# Test inputs that are not in any published archive. They are copied from the
# exact commit and must also appear, with their SHA-256, in the manifest.
REPOSITORY_INPUT_PREFIX = "verification/"
CONSUMER_TARGET_ARGUMENTS = ("--workspace", "--lib", "--bins", "--examples", "--all-features")
PACKAGED_TEST_ARGUMENTS = ("--workspace", "--all-targets", "--all-features")


def load_packaged_test_inputs(path: Path = PACKAGED_TEST_INPUTS_PATH) -> list[dict[str, str]]:
    """Read the reviewed list of files each packaged test target reads outside its package."""

    document = load_json_object(path)
    if set(document) != {"format", "inputs"} or document["format"] != PACKAGED_TEST_INPUTS_FORMAT:
        raise RcError(f"{path.name}: unexpected packaged test input format")
    entries = document["inputs"]
    if not isinstance(entries, list):
        raise RcError(f"{path.name}: inputs must be a list")
    keys = {"package", "target", "path", "sha256"}
    checked: list[dict[str, str]] = []
    hashes: dict[str, str] = {}
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != keys or not all(
            isinstance(entry[key], str) for key in keys
        ):
            raise RcError(f"{path.name}: malformed input entry")
        relative = PurePosixPath(entry["path"])
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or relative.as_posix() != entry["path"]
            or relative.parts[0] not in ("crates", REPOSITORY_INPUT_PREFIX.rstrip("/"))
            or re.fullmatch(r"[0-9a-f]{64}", entry["sha256"]) is None
        ):
            raise RcError(f"{path.name}: invalid input entry {entry['path']}")
        if hashes.setdefault(entry["path"], entry["sha256"]) != entry["sha256"]:
            raise RcError(f"{path.name}: one path has two digests: {entry['path']}")
        checked.append(dict(entry))
    if checked != sorted(checked, key=packaged_input_key) or len(
        {packaged_input_key(entry) for entry in checked}
    ) != len(checked):
        raise RcError(f"{path.name}: inputs must be sorted and unique")
    return checked


def packaged_input_key(entry: dict[str, str]) -> tuple[str, str, str]:
    return entry["package"], entry["target"], entry["path"]


def git_blob(path: str) -> bytes:
    data = run(["git", "cat-file", "blob", f"HEAD:{path}"], capture=True, binary=True)
    if not isinstance(data, bytes):
        raise RcError("git returned text for a blob")
    return data


def stage_repository_inputs(
    entries: list[dict[str, str]], layout_root: Path, read_blob=git_blob,
) -> list[dict[str, str]]:
    """Copy the listed non-archive inputs from the commit into the repository layout."""

    staged = []
    for path, digest in sorted({(entry["path"], entry["sha256"]) for entry in entries}):
        if not path.startswith(REPOSITORY_INPUT_PREFIX):
            continue
        data = read_blob(path)
        if hashlib.sha256(data).hexdigest() != digest:
            raise RcError(f"repository test input differs from the reviewed manifest: {path}")
        destination = layout_root / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
        staged.append({"path": path, "sha256": digest})
    return staged


def dep_info_prerequisites(path: Path) -> list[str] | None:
    """Return the prerequisites of a rustc dep-info file, or None for any other dep-info.

    Rustc's own file names itself as its first rule's target and lists only the
    files of that one compilation. Cargo's uplifted dep-info (`target/debug/x.d`)
    names the artifact instead and lists every dependency's sources; it is skipped.
    """

    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        separator = re.search(r"(?<!\\):(?:\s|$)", line)
        if separator is None:
            raise RcError(f"unreadable dep-info rule: {path.name}")
        if Path(line[:separator.start()].replace("\\ ", " ")).name != path.name:
            return None
        return [item.replace("\\ ", " ") for item in re.split(r"(?<!\\)\s+", line[separator.end():].strip()) if item]
    return None


def observed_cross_package_inputs(
    messages: str, layout_root: Path, target_dir: Path,
) -> tuple[list[dict[str, str]], list[str]]:
    """Derive, from rustc dep-info, every file a package target reads outside its package.

    Returns the test-target entries and a list of non-test violations. Files under the
    target directory are build-script output of the package itself.
    """

    test_targets: dict[str, tuple[str, str]] = {}
    for line in messages.splitlines():
        message = json.loads(line)
        if message.get("reason") != "compiler-artifact" or not message["profile"]["test"]:
            continue
        manifest = Path(message["manifest_path"]).resolve()
        if layout_root.resolve() not in manifest.parents:
            continue
        target = message["target"]
        label = f"{target['kind'][0]}:{target['name']}"
        test_targets[Path(message["filenames"][0]).name] = (message["target"]["src_path"], label)
    resolved_target = target_dir.resolve()
    dep_files = [*target_dir.glob("debug/deps/*.d"), *target_dir.glob("debug/examples/*.d"),
                 *target_dir.glob("debug/build/*/*.d")]
    entries: list[dict[str, str]] = []
    violations: list[str] = []
    seen_tests: set[str] = set()
    for dep_file in sorted(dep_files):
        prerequisites = dep_info_prerequisites(dep_file)
        if not prerequisites:
            continue
        root = Path(os.path.normpath(layout_root / prerequisites[0]))
        try:
            relative_root = root.relative_to(layout_root)
        except ValueError:
            continue
        if len(relative_root.parts) < 2 or relative_root.parts[0] != "crates":
            continue
        package = relative_root.parts[1]
        package_root = layout_root / "crates" / package
        test = test_targets.get(dep_file.stem)
        if test is not None:
            seen_tests.add(dep_file.stem)
        label = test[1] if test is not None else f"non-test:{relative_root.as_posix()}"
        for prerequisite in prerequisites:
            read = Path(os.path.normpath(layout_root / prerequisite))
            if read == package_root or package_root in read.parents:
                continue
            if resolved_target == read.resolve() or resolved_target in read.resolve().parents:
                continue
            try:
                relative = read.relative_to(layout_root).as_posix()
            except ValueError:
                relative = read.as_posix()
            if test is None:
                violations.append(f"{package} {label} reads {relative}")
                continue
            if not read.is_file():
                raise RcError(f"dep-info names a missing file: {relative}")
            entries.append({"package": package, "target": label, "path": relative,
                            "sha256": sha256(read)})
    missing = sorted(set(test_targets) - seen_tests)
    if missing:
        raise RcError(f"dep-info is missing for packaged test targets: {', '.join(missing)}")
    unique = {packaged_input_key(entry): entry for entry in entries}
    return [unique[key] for key in sorted(unique)], violations


def require_packaged_test_inputs(
    observed: list[dict[str, str]], expected: list[dict[str, str]], non_test: list[str],
) -> None:
    problems = [f"non-test target has a cross-package read: {item}" for item in non_test]
    expected_rows = {tuple(entry.values()) for entry in expected}
    observed_rows = {tuple(entry.values()) for entry in observed}
    problems.extend(f"unlisted cross-package test input: {' '.join(row)}"
                    for row in sorted(observed_rows - expected_rows))
    problems.extend(f"listed cross-package test input not read as listed: {' '.join(row)}"
                    for row in sorted(expected_rows - observed_rows))
    if problems:
        raise RcError("packaged test inputs differ from release/packaged-test-inputs.json:\n  "
                      + "\n  ".join(problems))


def repository_layout_reads(
    layout_manifest: Path, layout_root: Path, environment: dict[str, str],
) -> tuple[str, list[dict[str, str]], list[str]]:
    """Build every non-test and test target in the repository layout and derive cross-package reads.

    The non-test build comes first so that every library, binary, example and build
    script leaves its own dep-info, even when no test depends on it.
    """

    run(consumer_build_command(layout_manifest), environment=environment, cwd=layout_root)
    messages = run(packaged_test_command(layout_manifest), capture=True,
                   environment=environment, cwd=layout_root)
    if not isinstance(messages, str):
        raise RcError("packaged test build returned binary data")
    observed, non_test = observed_cross_package_inputs(
        messages, layout_root, Path(environment["CARGO_TARGET_DIR"]))
    return messages, observed, non_test


def write_packaged_workspace_manifest(root: Path, package_roots: dict[str, Path]) -> Path:
    workspace_manifest = root / "Cargo.toml"
    workspace_lines = ["[workspace]", 'resolver = "3"', "members = ["]
    for package_root in sorted(package_roots.values()):
        workspace_lines.append(f"  {json.dumps(package_root.relative_to(root).as_posix())},")
    workspace_lines.extend(["]", "", "[patch.crates-io]"])
    for name, package_root in sorted(package_roots.items()):
        workspace_lines.append(f"{json.dumps(name)} = {{ path = {json.dumps(str(package_root))} }}")
    workspace_manifest.write_text("\n".join(workspace_lines) + "\n", encoding="utf-8")
    return workspace_manifest


def consumer_build_command(workspace_manifest: Path) -> list[str]:
    return ["cargo", "+1.97.1", "build", "--manifest-path", str(workspace_manifest),
            *CONSUMER_TARGET_ARGUMENTS, "--locked", "--offline", "--jobs", "1"]


def packaged_test_command(workspace_manifest: Path) -> list[str]:
    return ["cargo", "+1.97.1", "test", "--manifest-path", str(workspace_manifest),
            *PACKAGED_TEST_ARGUMENTS, "--locked", "--offline", "--no-run", "--jobs", "1",
            "--message-format=json-render-diagnostics"]


def packaged_checker_inputs() -> list[dict[str, str]]:
    return [{"path": name, "sha256": sha256(ROOT / name)} for name in (
        "tools/rc_package.py", "tools/check_generated_application.py", "tools/check_synthesis.py",
        "Cargo.lock", "release/package-set.toml", "release/packaged-test-inputs.json",
        "tools/check_v1_compatibility.py",
        "test-data/v1-compatibility/baseline.json",
        "test-projects/external-consumer/src/main.rs", "test-projects/external-consumer/Cargo.toml",
    )]


def verify_packaged_workspace(
    packages_dir: Path,
    version: str,
    build_target: Path,
    environment: dict[str, str],
) -> dict[str, object]:
    build_target.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="packaged-workspace-", dir=build_target) as directory:
        return check_packaged_workspace(packages_dir, version, Path(directory), environment)


def check_packaged_workspace(
    packages_dir: Path, version: str, verification_root: Path, environment: dict[str, str],
) -> dict[str, object]:
    sources = verification_root / "sources"
    sources.mkdir(parents=True)
    commit = git_text("rev-parse", "HEAD")
    inputs = packaged_checker_inputs()
    clean = not git_text("status", "--porcelain", "--untracked-files=all")
    expected = {f"{name}-{version}.crate" for name in require_string_list(package_set(), "publish_order")}
    archives = sorted(packages_dir.glob("*.crate"))
    if {path.name for path in archives} != expected:
        raise RcError("packaged verification requires the exact declared crate set")
    package_roots: dict[str, Path] = {}
    package_evidence = []
    for archive_path in archives:
        extract_checked_crate(archive_path, sources)
        name = archive_path.stem.removesuffix(f"-{version}")
        package_root = sources / f"{name}-{version}"
        if not (package_root / "Cargo.toml").is_file():
            raise RcError(f"unpacked crate is missing Cargo.toml: {archive_path.name}")
        manifest = load_toml(package_root / "Cargo.toml")
        package = manifest.get("package", {})
        if not isinstance(package, dict) or (package.get("name"), package.get("version")) != (name, version):
            raise RcError(f"unpacked crate identity differs from its archive: {archive_path.name}")
        vcs = load_json_object(package_root / ".cargo_vcs_info.json")
        git_info = vcs.get("git")
        if not isinstance(git_info, dict) or git_info.get("sha1") != commit:
            raise RcError(f"crate source commit differs from this checkout: {archive_path.name}")
        dirty = git_info.get("dirty", False)
        if not isinstance(dirty, bool):
            raise RcError(f"crate source status is malformed: {archive_path.name}")
        package_evidence.append({"archive": archive_path.name, "sha256": sha256(archive_path),
                                 "source_clean": not dirty})
        package_roots[name] = package_root

    workspace_manifest = write_packaged_workspace_manifest(verification_root, package_roots)

    check_environment = remapped_compiler_environment(
        environment, verification_root, "/zeno-fcis-package-check",
    )
    target_dir = verification_root / "target"
    check_environment["CARGO_TARGET_DIR"] = str(target_dir)
    check_environment.update(CARGO_BUILD_JOBS="1", CARGO_INCREMENTAL="0",
                             CARGO_PROFILE_DEV_DEBUG="0", CARGO_PROFILE_TEST_DEBUG="0")
    graph = generated_application.resolve_reviewed_graph(
        verification_root,
        {(name, version): root / "Cargo.toml" for name, root in package_roots.items()},
        check_environment,
    )
    # 1. Consumer build, isolated layout: every target a consumer of a published
    #    crate builds (libraries, binaries, examples, build scripts) from the
    #    archives alone.
    run(consumer_build_command(workspace_manifest), environment=check_environment,
        cwd=verification_root)

    # 2. Packaged tests, repository layout: the same archives at crates/<name>/,
    #    plus only the verification files the reviewed manifest names. Every
    #    file a test reads outside its own package must equal that manifest.
    expected_test_inputs = load_packaged_test_inputs()
    layout_root = verification_root / "repository-layout"
    layout_roots = {name: layout_root / "crates" / name for name in package_roots}
    for name, package_root in package_roots.items():
        shutil.copytree(package_root, layout_roots[name])
    repository_inputs = stage_repository_inputs(expected_test_inputs, layout_root)
    layout_manifest = write_packaged_workspace_manifest(layout_root, layout_roots)
    layout_graph = generated_application.resolve_reviewed_graph(
        layout_root,
        {(name, version): root / "Cargo.toml" for name, root in layout_roots.items()},
        check_environment,
    )
    if layout_graph != graph:
        raise RcError("repository-layout graph differs from the isolated packaged graph")
    _, observed_test_inputs, non_test_reads = repository_layout_reads(
        layout_manifest, layout_root, check_environment,
    )
    require_packaged_test_inputs(observed_test_inputs, expected_test_inputs, non_test_reads)
    run(["cargo", "+1.97.1", "build", "--locked", "--offline", "-p", "zeno-fcis-cli",
         "--bin", "zeno-fcis"], environment=check_environment, cwd=verification_root)
    executable = verification_root / "target" / "debug" / ("zeno-fcis.exe" if os.name == "nt" else "zeno-fcis")
    application_root = verification_root / "generated-application"
    application_root.mkdir()
    app = application_root / "counter"
    run([str(executable), "new", str(app), "--template", "durable-counter"],
        environment=check_environment, cwd=application_root)
    application = generated_application.exercise_application(
        app, application_root, package_roots, version, check_environment, [str(executable)],
    )
    prepared_root = verification_root / "prepared-application"
    prepared_root.mkdir()
    prepared_app = prepared_root / "counter"
    run([str(executable), "new", str(prepared_app), "--template", "prepared-counter"],
        environment=check_environment, cwd=prepared_root)
    prepared_application = generated_application.exercise_prepared_application(
        prepared_app, prepared_root, package_roots, version, check_environment, [str(executable)],
    )
    examples = {}
    for template in generated_application.EXAMPLE_TEMPLATES:
        example_root = verification_root / f"{template}-application"
        example_root.mkdir()
        example_app = example_root / "app"
        run([str(executable), "new", str(example_app), "--template", template],
            environment=check_environment, cwd=example_root)
        examples[template] = generated_application.exercise_example_application(
            template, example_app, example_root, package_roots, version, check_environment,
            [str(executable)],
        )
    v1_consumer = generated_application.exercise_v1_consumer(
        verification_root, package_roots, version, check_environment,
    )
    compiler = run(["rustc", "+1.97.1", "-vV"], capture=True)
    if (packaged_checker_inputs() != inputs or git_text("rev-parse", "HEAD") != commit
            or (not git_text("status", "--porcelain", "--untracked-files=all")) != clean):
        raise RcError("checker inputs or source status changed during packaged verification")
    result = {
        "format": "zeno-fcis/packaged-application/1", "status": "passed",
        "source_commit": commit, "checker_source_clean": clean, "checker_inputs": inputs,
        "version": version, "compiler": compiler,
        "compiler_flags": compiler_flag_evidence(check_environment, verification_root, "<verification-root>"),
        "archives": package_evidence, "packaged_workspace_graph": graph,
        "consumer_build": {
            "layout": "sources/<crate>-<version>/, archives only",
            "command": ["cargo", "+1.97.1", "build", "--manifest-path", "<isolated-workspace>/Cargo.toml",
                        *CONSUMER_TARGET_ARGUMENTS, "--locked", "--offline", "--jobs", "1"],
        },
        "packaged_tests": {
            "layout": "crates/<crate>/ from the same archives, plus the listed verification files",
            "command": ["cargo", "+1.97.1", "test", "--manifest-path", "<repository-layout>/Cargo.toml",
                        *PACKAGED_TEST_ARGUMENTS, "--locked", "--offline", "--no-run", "--jobs", "1"],
            "test_inputs_manifest_sha256": sha256(PACKAGED_TEST_INPUTS_PATH),
            "cross_package_inputs": observed_test_inputs,
            "repository_inputs": repository_inputs,
            "standalone_tests": False,
        },
        "generator": {"package": "zeno-fcis-cli", "target": "zeno-fcis", "sha256": sha256(executable),
                      "command": ["<packaged-cli>", "new", "<new-application>", "--template", "durable-counter"]},
        "internal_manifests": [{"name": name, "version": version,
                                "path": (root / "Cargo.toml").relative_to(verification_root).as_posix()}
                               for name, root in sorted(package_roots.items())],
        "application": application,
        "prepared_application": prepared_application,
        "example_applications": examples,
        "v1_consumer": v1_consumer,
        "nonclaims": ["not a registry-only installation check", "not fresh external dependency resolution",
                      "packaged tests are not standalone: they compile only in the repository layout "
                      "with the listed verification files; the whole-repository source archive runs every test",
                      "not an independent review",
                      "not production deployment qualification", "not release authorization"],
    }
    return result


def verify_packaged(packages: Path, output: Path, version: str) -> None:
    output.mkdir(parents=True)
    target = output / ".cargo-target"
    try:
        result = verify_packaged_workspace(packages, version, target, dict(os.environ))
        write_json(output / "PACKAGED-APPLICATION.json", result)
        target.rmdir()
    except BaseException:
        # The exclusive mkdir above establishes ownership before cleanup.
        shutil.rmtree(output)
        raise
    print(f"rc-package: packaged application PASS; receipt: {output / 'PACKAGED-APPLICATION.json'}")


def build(output: Path) -> None:
    configured, _ = validate_package_set()
    version = require_string(configured, "version")
    commit = require_clean_commit()
    run([sys.executable, "tools/check_release_privacy.py", "check"])
    if output.exists() and any(output.iterdir()):
        raise RcError("output directory must not exist or must be empty")
    output.mkdir(parents=True, exist_ok=True)
    packages_dir = output / "packages"
    binaries_dir = output / "binaries"
    docs_dir = output / "docs"
    source_dir = output / "source"
    for directory in (packages_dir, binaries_dir, docs_dir, source_dir):
        directory.mkdir()
    build_target = output / ".cargo-target"
    build_environment = remapped_compiler_environment(
        dict(os.environ), ROOT, "/zeno-fcis-source",
    )
    build_environment["CARGO_TARGET_DIR"] = str(build_target)

    run(
        ["cargo", "+1.97.1", "fetch", "--locked"],
        environment=build_environment,
    )

    source_manifest_text = run(
        ["python3", "tools/release_manifest.py", "--require-clean"], capture=True
    )
    if not isinstance(source_manifest_text, str):
        raise RcError("source manifest returned binary data")
    source_manifest = output / "SOURCE-MANIFEST.json"
    source_manifest.write_text(source_manifest_text, encoding="utf-8")

    package_arguments = [
        "cargo",
        "+1.97.1",
        "package",
        "--workspace",
        "--locked",
        "--no-verify",
    ]
    for private_name in require_string_list(configured, "private_packages"):
        package_arguments.extend(["--exclude", private_name])
    run(package_arguments, environment=build_environment)
    for name in require_string_list(configured, "publish_order"):
        archive = build_target / "package" / f"{name}-{version}.crate"
        if not archive.is_file():
            raise RcError(f"cargo did not create {archive.name}")
        shutil.copyfile(archive, packages_dir / archive.name)
    packaged_application = verify_packaged_workspace(packages_dir, version, build_target, build_environment)
    write_json(output / "PACKAGED-APPLICATION.json", packaged_application)

    rustdoc_environment = remapped_compiler_environment(
        build_environment, build_target, "/zeno-fcis-target",
    )
    rustdoc_arguments = [
        "cargo",
        "+1.97.1",
        "doc",
        "--workspace",
        "--all-features",
        "--locked",
        "--no-deps",
        "--jobs",
        "1",
    ]
    for private_name in require_string_list(configured, "private_packages"):
        rustdoc_arguments.extend(["--exclude", private_name])
    run(rustdoc_arguments, environment=rustdoc_environment)
    if (build_target / "doc" / "zeno_fcis_generated_code_tests").exists():
        raise RcError("private generated-code test crate leaked into public rustdoc")
    normalize_rustdoc_tree(build_target / "doc")
    deterministic_tree_archive(
        build_target / "doc",
        docs_dir / f"zeno-fcis-rustdoc-{version}.tar.gz",
        f"zeno-fcis-rustdoc-{version}",
    )

    verbose_version = run(["rustc", "+1.97.1", "-vV"], capture=True)
    if not isinstance(verbose_version, str):
        raise RcError("rustc version output is binary")
    host_lines = [
        line.removeprefix("host: ")
        for line in verbose_version.splitlines()
        if line.startswith("host: ")
    ]
    if len(host_lines) != 1:
        raise RcError("rustc host target is unavailable")
    host = host_lines[0]
    host_targets = {host}
    binary_inventory = binary_artifact_inventory(configured, version, host)
    for item in binary_inventory:
        package_name = item["package"]
        target_name = item["target"]
        run(
            [
                "cargo",
                "+1.97.1",
                "build",
                "--release",
                "--locked",
                "-p",
                package_name,
                "--bin",
                target_name,
            ],
            environment=build_environment,
        )
        executable_name = f"{target_name}.exe" if os.name == "nt" else target_name
        executable = build_target / "release" / executable_name
        if not executable.is_file():
            raise RcError(f"release binary {executable_name} is missing")
        deterministic_binary_archive(
            executable,
            binaries_dir / item["archive"],
            item["prefix"],
        )
    actual_binary_archives = sorted(path.name for path in binaries_dir.iterdir())
    expected_binary_archives = sorted(item["archive"] for item in binary_inventory)
    if actual_binary_archives != expected_binary_archives:
        raise RcError(
            "assembled binary archive set differs from the declared inventory"
        )
    shutil.rmtree(build_target)

    source_archive(
        source_dir / f"zeno-fcis-{version}-source.tar.gz",
        f"zeno-fcis-{version}",
    )

    complete_metadata = cargo_metadata(complete=True)
    sbom_path = output / "SBOM.cdx.json"
    write_json(sbom_path, build_sbom(complete_metadata, commit, version))
    if require_clean_commit() != commit:
        raise RcError("source commit changed during release assembly")

    provenance_inputs = {
        "format": "zeno-fcis/provenance-inputs/1",
        "version": version,
        "source_commit": commit,
        "rust_toolchain": "1.97.1",
        "host_targets": sorted(host_targets),
        "source_manifest_sha256": sha256(source_manifest),
        "packaged_test_inputs_sha256": sha256(PACKAGED_TEST_INPUTS_PATH),
        "sbom_sha256": sha256(sbom_path),
        "compiler_flags": {
            "native": compiler_flag_evidence(build_environment, ROOT, "<source>"),
            "packaged_application": packaged_application["compiler_flags"],
            "rustdoc": compiler_flag_evidence(rustdoc_environment, build_target, "<target>"),
        },
        "commands": [
            "cargo +1.97.1 fetch --locked",
            " ".join(package_arguments),
            "cargo +1.97.1 metadata --manifest-path <isolated-workspace and repository-layout>/Cargo.toml --offline --format-version 1 (seeded and checked against the reviewed lock)",
            "cargo +1.97.1 build --manifest-path <isolated-workspace>/Cargo.toml --workspace --lib --bins --examples --all-features --locked --offline --jobs 1 (sources/<crate>-<version>/, archives only)",
            "cargo +1.97.1 test --manifest-path <repository-layout>/Cargo.toml --workspace --all-targets --all-features --locked --offline --no-run --jobs 1 (crates/<crate>/ plus the verification files in release/packaged-test-inputs.json; every cross-package read must equal that manifest)",
            "cargo +1.97.1 build --manifest-path <isolated-workspace>/Cargo.toml --locked --offline -p zeno-fcis-cli --bin zeno-fcis",
            "<packaged-cli> new <new-application> --template durable-counter",
            "generated application: archive-only internal sources, reviewed external lock, formatting, Clippy, tests and durable demonstration; see PACKAGED-APPLICATION.json",
            *[item["command"] for item in binary_inventory],
            " ".join(rustdoc_arguments),
        ],
        "nonclaim": "inputs for a future signed attestation; not a signature or SLSA provenance",
    }
    write_json(output / "PROVENANCE-INPUTS.json", provenance_inputs)

    manifest_path = output / "RC-MANIFEST.json"
    checksums_path = output / "SHA256SUMS"
    bundle_path = output / f"zeno-fcis-{version}-rc-bundle.zip"
    entries = artifact_entries(output, {manifest_path, checksums_path, bundle_path})
    write_json(
        manifest_path,
        {
            "format": "zeno-fcis/release-candidate-manifest/1",
            "version": version,
            "source_commit": commit,
            "rust_toolchain": "1.97.1",
            "artifacts": entries,
            "nonclaims": [
                "not a production deployment authorization",
                "not an independent audit",
                "not a signature or SLSA attestation",
            ],
        },
    )
    checksum_files = [
        path
        for path in sorted(item for item in output.rglob("*") if item.is_file())
        if path not in {checksums_path, bundle_path}
    ]
    checksums_path.write_text(
        "".join(
            f"{sha256(path)}  {path.relative_to(output).as_posix()}\n"
            for path in checksum_files
        ),
        encoding="utf-8",
    )
    deterministic_bundle(output, bundle_path)
    run([sys.executable, "tools/check_release_privacy.py", "check", str(output)])
    print(
        f"rc-package: built {len(require_string_list(configured, 'publish_order'))} "
        f"crate packages and {len(entries)} retained artifacts at {commit}"
    )


def main() -> int:
    args = parse_args()
    try:
        configured, _ = validate_package_set()
        if args.command == "check":
            run([sys.executable, "tools/check_release_privacy.py", "check"])
            print(
                "rc-package: PASS "
                f"({len(require_string_list(configured, 'publish_order'))} public, "
                f"{len(require_string_list(configured, 'private_packages'))} private, "
                f"version {require_string(configured, 'version')})"
            )
        elif args.command == "self-test":
            run([sys.executable, "tools/test_release_privacy.py"])
            run_self_test(configured, cargo_metadata(complete=False))
            run_rustdoc_normalization_self_test()
            run_packaged_layout_self_test()
            run_tree_archive_mode_self_test()
            run_binary_inventory_self_test(configured)
            print(
                "rc-package: self-test PASS "
                "(12 hostile mutations rejected; 4 packaged layout controls refused; "
                "rustdoc, archive modes, and binary inventory verified)"
            )
        elif args.command == "verify-packaged":
            verify_packaged(args.packages.resolve(), args.output.resolve(), require_string(configured, "version"))
        else:
            build(args.output.resolve())
        return 0
    except (
        RcError,
        RuntimeError,
        OSError,
        subprocess.CalledProcessError,
        json.JSONDecodeError,
        tomllib.TOMLDecodeError,
        tarfile.TarError,
    ) as error:
        print(f"rc-package: FAIL: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
