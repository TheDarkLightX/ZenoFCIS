def cargo_metadata(*, complete: bool) -> dict[str, object]:
    arguments = [
        "cargo",
        "+1.97.1",
        "metadata",
        "--format-version",
        "1",
        "--locked",
    ]
    if not complete:
        arguments.append("--no-deps")
    encoded = run(arguments, capture=True)
    if not isinstance(encoded, str):
        raise RcError("cargo metadata did not return text")
    document = json.loads(encoded)
    if not isinstance(document, dict):
        raise RcError("cargo metadata is not an object")
    return document


def require_string(document: dict[str, object], field: str) -> str:
    value = document.get(field)
    if not isinstance(value, str) or not value:
        raise RcError(f"package-set field {field!r} must be a nonempty string")
    return value


def require_string_list(document: dict[str, object], field: str) -> list[str]:
    value = document.get(field)
    if not isinstance(value, list) or not all(
        isinstance(item, str) and item for item in value
    ):
        raise RcError(f"package-set field {field!r} must be a string list")
    return list(value)


def workspace_packages(metadata: dict[str, object]) -> list[dict[str, object]]:
    packages = metadata.get("packages")
    members = metadata.get("workspace_members")
    if not isinstance(packages, list) or not isinstance(members, list):
        raise RcError("cargo metadata omits workspace packages")
    member_ids = set(members)
    selected = [
        package
        for package in packages
        if isinstance(package, dict) and package.get("id") in member_ids
    ]
    if len(selected) != len(member_ids):
        raise RcError("cargo metadata workspace member set is incomplete")
    return selected


def validate_package_documents(
    configured: dict[str, object], metadata: dict[str, object]
) -> tuple[dict[str, object], dict[str, object]]:
    packages = workspace_packages(metadata)
    version = require_string(configured, "version")
    toolchain = require_string(configured, "rust_toolchain")
    if toolchain != "1.97.1":
        raise RcError("release candidates must use pinned Rust 1.97.1")

    order = require_string_list(configured, "publish_order")
    private = require_string_list(configured, "private_packages")
    if len(order) != len(set(order)):
        raise RcError("publish order contains a duplicate")
    if len(private) != len(set(private)):
        raise RcError("private package set contains a duplicate")

    by_name: dict[str, dict[str, object]] = {}
    for package in packages:
        name = package.get("name")
        if not isinstance(name, str) or name in by_name:
            raise RcError("workspace package names are invalid or duplicated")
        by_name[name] = package

    public_actual = {
        name for name, package in by_name.items() if package.get("publish") != []
    }
    private_actual = set(by_name).difference(public_actual)
    if set(order) != public_actual:
        missing = sorted(public_actual.difference(order))
        extra = sorted(set(order).difference(public_actual))
        raise RcError(f"publish set mismatch: missing={missing}, extra={extra}")
    if set(private) != private_actual:
        raise RcError(
            "private package mismatch: "
            f"expected={sorted(private_actual)}, configured={sorted(private)}"
        )

    order_index = {name: index for index, name in enumerate(order)}
    for name, package in by_name.items():
        if package.get("version") != version:
            raise RcError(f"{name}: package version is not {version}")
        if package.get("rust_version") != toolchain:
            raise RcError(f"{name}: rust-version is not {toolchain}")
        for field in ("description", "license", "repository", "readme"):
            value = package.get(field)
            if not isinstance(value, str) or not value:
                raise RcError(f"{name}: missing package metadata {field}")
        manifest_path = package.get("manifest_path")
        if not isinstance(manifest_path, str) or not manifest_path:
            raise RcError(f"{name}: package manifest path is unavailable")
        readme = Path(manifest_path).parent / str(package["readme"])
        if not readme.is_file():
            raise RcError(f"{name}: package README does not exist")

        dependencies = package.get("dependencies")
        if not isinstance(dependencies, list):
            raise RcError(f"{name}: dependency metadata is malformed")
        for dependency in dependencies:
            if not isinstance(dependency, dict):
                raise RcError(f"{name}: dependency metadata is malformed")
            dependency_name = dependency.get("name")
            if dependency_name not in by_name:
                continue
            if dependency.get("req") != f"={version}":
                raise RcError(
                    f"{name}: internal dependency {dependency_name} is not pinned "
                    f"to ={version}"
                )
            if (
                name in order_index
                and dependency_name in order_index
                and order_index[str(dependency_name)] >= order_index[name]
            ):
                raise RcError(
                    f"{name}: dependency {dependency_name} is not earlier in "
                    "publish_order"
                )

    binaries = configured.get("binaries")
    if not isinstance(binaries, list) or not binaries:
        raise RcError("package set must declare at least one binary")
    binary_targets: set[str] = set()
    for binary in binaries:
        if not isinstance(binary, dict):
            raise RcError("binary declaration is malformed")
        package_name = binary.get("package")
        target_name = binary.get("target")
        if (
            package_name not in by_name
            or not isinstance(target_name, str)
            or not target_name
            or not target_name.isascii()
            or any(
                not character.isalnum() and character not in "-_"
                for character in target_name
            )
        ):
            raise RcError("binary package or target is invalid")
        if target_name in binary_targets:
            raise RcError(f"duplicate binary target {target_name}")
        binary_targets.add(target_name)
        targets = by_name[str(package_name)].get("targets")
        if not isinstance(targets, list) or not any(
            isinstance(target, dict)
            and target.get("name") == target_name
            and "bin" in target.get("kind", [])
            for target in targets
        ):
            raise RcError(f"missing binary target {package_name}/{target_name}")

    return configured, metadata


def validate_package_set() -> tuple[dict[str, object], dict[str, object]]:
    source_snapshots.check(ROOT)
    # BEGIN refuse unlisted knowledge before invoking Cargo.
    if knowledge_files.check(ROOT):
        raise RcError("knowledge file include policy failed")
    # END knowledge include preflight.
    configured, metadata = validate_package_documents(
        package_set(), cargo_metadata(complete=False)
    )
    validate_developer_tooling(require_string(configured, "version"))
    validate_scaffold_versions(require_string(configured, "version"))
    return configured, metadata


def validate_scaffold_versions(version: str, root: Path = ROOT) -> None:
    """Check emitted dependency pins before any release build or app journey."""
    package_roots = {
        str(tomllib.loads(path.read_text())["package"]["name"]): path.parent
        for path in (root / "crates").glob("*/Cargo.toml")
    }
    templates = root / "crates/zeno-fcis-cli/templates"
    paths = [directory / "Cargo.toml.in" for directory in sorted(templates.iterdir())
             if directory.is_dir()]
    if not paths:
        raise RcError("release has no application templates")
    paths.append(root / "crates/zeno-fcis-cli/contract-app/Cargo.toml.in")
    for path in paths:
        document = tomllib.loads(path.read_text().replace("{version}", version))
        try:
            selected = generated_application.generated_dependency_closure(document, package_roots, version)
        except RuntimeError as error:
            raise RcError(f"{path.relative_to(root)}: {error}") from error
        if not selected:
            raise RcError(f"{path.relative_to(root)}: no library dependency pins")


def run_self_test(configured: dict[str, object], metadata: dict[str, object]) -> None:
    def expect_failure(
        changed_configured: dict[str, object],
        changed_metadata: dict[str, object],
        label: str,
    ) -> None:
        try:
            validate_package_documents(changed_configured, changed_metadata)
        except RcError:
            return
        raise RcError(f"self-test mutation survived: {label}")

    duplicate_configured = copy.deepcopy(configured)
    duplicate_order = require_string_list(duplicate_configured, "publish_order")
    duplicate_order.append(duplicate_order[0])
    duplicate_configured["publish_order"] = duplicate_order
    expect_failure(duplicate_configured, copy.deepcopy(metadata), "duplicate package")

    reversed_configured = copy.deepcopy(configured)
    reversed_configured["publish_order"] = list(
        reversed(require_string_list(reversed_configured, "publish_order"))
    )
    expect_failure(
        reversed_configured, copy.deepcopy(metadata), "invalid publish order"
    )

    dev_order_configured = copy.deepcopy(configured)
    dev_order = require_string_list(dev_order_configured, "publish_order")
    crypto_index = dev_order.index("zeno-fcis-crypto")
    spec_index = dev_order.index("zeno-fcis-spec")
    dev_order[crypto_index], dev_order[spec_index] = (
        dev_order[spec_index],
        dev_order[crypto_index],
    )
    dev_order_configured["publish_order"] = dev_order
    expect_failure(
        dev_order_configured,
        copy.deepcopy(metadata),
        "dev dependency publish order",
    )

    wrong_version_metadata = copy.deepcopy(metadata)
    wrong_version_packages = wrong_version_metadata.get("packages")
    if not isinstance(wrong_version_packages, list) or not wrong_version_packages:
        raise RcError("self-test package set is unavailable")
    first_package = wrong_version_packages[0]
    if not isinstance(first_package, dict):
        raise RcError("self-test package is malformed")
    first_package["version"] = "9.9.9"
    expect_failure(copy.deepcopy(configured), wrong_version_metadata, "package version")

    wrong_rust_metadata = copy.deepcopy(metadata)
    rust_packages = workspace_packages(wrong_rust_metadata)
    rust_packages[0]["rust_version"] = "1.97"
    expect_failure(copy.deepcopy(configured), wrong_rust_metadata, "minimum Rust version")

    missing_readme_metadata = copy.deepcopy(metadata)
    missing_readme_packages = missing_readme_metadata.get("packages")
    if not isinstance(missing_readme_packages, list) or not missing_readme_packages:
        raise RcError("self-test package set is unavailable")
    readme_package = missing_readme_packages[0]
    if not isinstance(readme_package, dict):
        raise RcError("self-test package is malformed")
    readme_package["readme"] = "missing-release-readme.md"
    expect_failure(copy.deepcopy(configured), missing_readme_metadata, "package README")

    package = load_json_object(NPM_PACKAGE_PATH)
    lock = load_json_object(NPM_LOCK_PATH)
    wrong_probity = copy.deepcopy(package)
    wrong_probity["devDependencies"] = {"@nizos/probity": "9.9.9"}
    try:
        validate_developer_tooling_documents(
            wrong_probity,
            lock,
            PROBITY_CONFIG_PATH.read_text(encoding="utf-8"),
            NODE_VERSION_PATH.read_text(encoding="utf-8"),
            require_string(configured, "version"),
        )
    except RcError:
        pass
    else:
        raise RcError("self-test mutation survived: Probity version")

    for changed_override in ({}, {"@modelcontextprotocol/sdk": "1.30.0"}):
        wrong_override = copy.deepcopy(package)
        wrong_override["overrides"] = changed_override
        try:
            validate_developer_tooling_documents(
                wrong_override,
                lock,
                PROBITY_CONFIG_PATH.read_text(encoding="utf-8"),
                NODE_VERSION_PATH.read_text(encoding="utf-8"),
                require_string(configured, "version"),
            )
        except RcError as error:
            if "patched MCP SDK" not in str(error):
                raise RcError("self-test override mutation failed for an unrelated reason") from error
        else:
            raise RcError("self-test mutation survived: patched MCP SDK override")

    changed_transitive_lock = copy.deepcopy(lock)
    changed_transitive_packages = changed_transitive_lock.get("packages")
    if not isinstance(changed_transitive_packages, dict):
        raise RcError("self-test npm packages map is unavailable")
    changed_transitive = changed_transitive_packages.get(
        "node_modules/@openai/codex-sdk"
    )
    if not isinstance(changed_transitive, dict):
        raise RcError("self-test could not find a transitive npm package")
    changed_transitive["version"] = "9.9.9"
    changed_transitive["integrity"] = "sha512-hostile-lock-graph-mutation"
    try:
        validate_developer_tooling_documents(
            package,
            changed_transitive_lock,
            PROBITY_CONFIG_PATH.read_text(encoding="utf-8"),
            NODE_VERSION_PATH.read_text(encoding="utf-8"),
            require_string(configured, "version"),
        )
    except RcError:
        pass
    else:
        raise RcError("self-test mutation survived: transitive npm lock graph")

    wrong_pin_metadata = copy.deepcopy(metadata)
    wrong_pin_packages = wrong_pin_metadata.get("packages")
    changed_pin = False
    if isinstance(wrong_pin_packages, list):
        workspace_names = {
            package.get("name")
            for package in wrong_pin_packages
            if isinstance(package, dict)
        }
        for package in wrong_pin_packages:
            if not isinstance(package, dict):
                continue
            dependencies = package.get("dependencies")
            if not isinstance(dependencies, list):
                continue
            for dependency in dependencies:
                if (
                    isinstance(dependency, dict)
                    and dependency.get("name") in workspace_names
                ):
                    dependency["req"] = "*"
                    changed_pin = True
                    break
            if changed_pin:
                break
    if not changed_pin:
        raise RcError("self-test could not find an internal dependency")
    expect_failure(copy.deepcopy(configured), wrong_pin_metadata, "dependency pin")

    hidden_public_metadata = copy.deepcopy(metadata)
    hidden_packages = hidden_public_metadata.get("packages")
    if not isinstance(hidden_packages, list):
        raise RcError("self-test package set is unavailable")
    private_test_package = next(
        (
            package
            for package in hidden_packages
            if isinstance(package, dict)
            and package.get("name") == "zeno-fcis-generated-code-tests"
        ),
        None,
    )
    if private_test_package is None:
        raise RcError("self-test generated-code test package is unavailable")
    private_test_package["publish"] = None
    expect_failure(
        copy.deepcopy(configured), hidden_public_metadata, "hidden public package"
    )

    wrong_binary_configured = copy.deepcopy(configured)
    binaries = wrong_binary_configured.get("binaries")
    if (
        not isinstance(binaries, list)
        or not binaries
        or not isinstance(binaries[0], dict)
    ):
        raise RcError("self-test binary declaration is unavailable")
    binaries[0]["target"] = "missing-binary"
    expect_failure(wrong_binary_configured, copy.deepcopy(metadata), "binary target")

    duplicate_binary_configured = copy.deepcopy(configured)
    duplicate_binaries = duplicate_binary_configured.get("binaries")
    if not isinstance(duplicate_binaries, list) or not duplicate_binaries:
        raise RcError("self-test binary declaration is unavailable")
    duplicate_binaries.append(copy.deepcopy(duplicate_binaries[0]))
    expect_failure(
        duplicate_binary_configured,
        copy.deepcopy(metadata),
        "duplicate binary target",
    )


def run_packaged_layout_self_test() -> None:
    """Planted controls for the consumer build and the cross-package test input manifest."""

    def package(directory: Path, name: str, library: str, test: str | None = None) -> Path:
        (directory / "src").mkdir(parents=True)
        (directory / "Cargo.toml").write_text(
            f'[package]\nname = "{name}"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n',
            encoding="utf-8",
        )
        (directory / "src" / "lib.rs").write_text(library, encoding="utf-8")
        (directory / "data.txt").write_text(f"{name} data\n", encoding="utf-8")
        if test is not None:
            (directory / "tests").mkdir()
            (directory / "tests" / "reads.rs").write_text(test, encoding="utf-8")
        return directory

    def workspace(root: Path, roots: dict[str, Path], environment: dict[str, str]) -> Path:
        manifest = write_packaged_workspace_manifest(root, roots)
        run(["cargo", "+1.97.1", "generate-lockfile", "--manifest-path", str(manifest), "--offline"],
            environment=environment, cwd=root)
        return manifest

    def layout_reads(root: Path, roots: dict[str, Path], environment: dict[str, str]):
        return repository_layout_reads(workspace(root, roots, environment), root, environment)

    def refused(action, label: str) -> None:
        try:
            action()
        except (RcError, subprocess.CalledProcessError):
            return
        raise RcError(f"packaged layout self-test accepted {label}")

    sibling_read = 'pub const DATA: &str = include_str!("../../beta/data.txt");\n'
    test_reads = (
        "#[test]\nfn reads() {\n"
        '    assert!(!include_str!("../../beta/data.txt").is_empty());\n'
        '    assert!(!include_str!("../../../verification/fixture.txt").is_empty());\n}\n'
    )
    fixture = b"reviewed fixture\n"
    with tempfile.TemporaryDirectory(prefix="zeno-fcis-packaged-layout-self-test-") as raw:
        base = Path(raw)

        # The arithmetic allowance is a fixed file list, not an examples/ or
        # tools/ directory allowance. The listed bytes are still hash-checked.
        named = sorted(REPOSITORY_INPUT_FILES)[0]
        entry = {"package": "alpha", "target": "test:reads", "path": named,
                 "sha256": hashlib.sha256(fixture).hexdigest()}
        manifest = base / "test-inputs.json"
        write_json(manifest, {"format": PACKAGED_TEST_INPUTS_FORMAT, "inputs": [entry]})
        reviewed = load_packaged_test_inputs(manifest)
        stage_repository_inputs(reviewed, base / "named-input", read_blob=lambda path: fixture)
        if (base / "named-input" / named).read_bytes() != fixture:
            raise RcError("named repository test input was not staged exactly")
        entry["path"] = str(PurePosixPath(named).parent / "unlisted-fixture.txt")
        write_json(manifest, {"format": PACKAGED_TEST_INPUTS_FORMAT, "inputs": [entry]})
        refused(lambda: load_packaged_test_inputs(manifest), "an unlisted arithmetic fixture")

        def environment(name: str) -> dict[str, str]:
            return dict(os.environ, CARGO_TARGET_DIR=str(base / f"target-{name}"),
                        CARGO_INCREMENTAL="0", CARGO_PROFILE_DEV_DEBUG="0", CARGO_PROFILE_TEST_DEBUG="0")

        # Control 1: a library reading a sibling file cannot build from the archives alone.
        isolated = base / "isolated"
        consumer_env = environment("consumer")
        consumer_manifest = workspace(isolated, {
            "alpha": package(isolated / "sources" / "alpha-0.1.0", "alpha", sibling_read),
            "beta": package(isolated / "sources" / "beta-0.1.0", "beta", ""),
        }, consumer_env)
        refused(lambda: run(consumer_build_command(consumer_manifest), environment=consumer_env,
                            cwd=isolated), "a library reading a sibling package file")

        # Repository layout: one test reads a sibling archive file and a verification file.
        layout = base / "layout"
        roots = {"alpha": package(layout / "crates" / "alpha", "alpha", "", test_reads),
                 "beta": package(layout / "crates" / "beta", "beta", "")}
        sibling_digest = hashlib.sha256(b"beta data\n").hexdigest()
        expected = [
            {"package": "alpha", "target": "test:reads", "path": "crates/beta/data.txt",
             "sha256": sibling_digest},
            {"package": "alpha", "target": "test:reads", "path": "verification/fixture.txt",
             "sha256": hashlib.sha256(fixture).hexdigest()},
        ]
        stage_repository_inputs(expected, layout, read_blob=lambda path: fixture)
        messages, observed, non_test = layout_reads(layout, roots, environment("layout"))
        require_packaged_test_inputs(observed, expected, non_test)

        # Control 2: an unlisted cross-package read in a test fails the manifest check.
        refused(lambda: require_packaged_test_inputs(observed, expected[1:], non_test),
                "an unlisted cross-package test read")
        # Control 3: a changed verification fixture fails, whether staged or read.
        refused(lambda: stage_repository_inputs(expected, base / "restaged",
                                                read_blob=lambda path: fixture + b"changed"),
                "a verification input that differs from the manifest")
        (layout / "verification" / "fixture.txt").write_bytes(fixture + b"changed")
        changed, changed_non_test = observed_cross_package_inputs(
            messages, layout, base / "target-layout")
        refused(lambda: require_packaged_test_inputs(changed, expected, changed_non_test),
                "a changed verification fixture")

        # Each Rust compile-time input form must fail even when a sibling is
        # present and compilation succeeds. The actual release check derives
        # these reads from rustc dep-info for every published package target.
        for form, library in (
            ("include-str", sibling_read),
            ("include-bytes", 'pub const DATA: &[u8] = include_bytes!("../../beta/data.txt");\n'),
            ("include", 'include!("../../beta/src/lib.rs");\n'),
            ("path", '#[path = "../../beta/src/lib.rs"] pub mod external;\n'),
        ):
            mixed = base / form
            mixed_roots = {"gamma": package(mixed / "crates" / "gamma", "gamma", library),
                           "beta": package(mixed / "crates" / "beta", "beta", "")}
            _, observed, non_test = layout_reads(mixed, mixed_roots, environment(form))
            if not non_test:
                raise RcError(f"packaged layout self-test missed an external {form} read")
            refused(lambda: require_packaged_test_inputs(observed, observed, non_test),
                    f"a non-test cross-package {form} read")


