def normalize_rustdoc_tree(doc_root: Path) -> None:
    if not (doc_root / "zeno_fcis" / "index.html").is_file():
        raise RcError("public umbrella rustdoc is missing")
    search_index = doc_root / "search.index"
    if not (search_index / "root.js").is_file():
        raise RcError("rustdoc search index is missing before normalization")
    shutil.rmtree(search_index)

    marker = 'data-current-crate="'
    for name in ("help.html", "settings.html"):
        page = doc_root / name
        if not page.is_file():
            raise RcError(f"rustdoc helper page {name} is missing")
        content = page.read_text(encoding="utf-8")
        if content.count(marker) != 1:
            raise RcError(f"rustdoc helper page {name} has an unexpected shape")
        start = content.index(marker) + len(marker)
        end = content.find('"', start)
        if end < 0:
            raise RcError(f"rustdoc helper page {name} has no crate marker terminator")
        page.write_text(content[:start] + "zeno_fcis" + content[end:], encoding="utf-8")

    (doc_root / "OFFLINE_SEARCH_DISABLED.txt").write_text(
        RUSTDOC_ARCHIVE_NOTICE, encoding="utf-8"
    )


def deterministic_binary_archive(binary: Path, destination: Path, prefix: str, root: Path = ROOT) -> None:
    members = [
        (binary, binary.name, 0o755),
        (root / "README.md", "README.md", 0o644),
        *((root / name, name, 0o644) for name in ATTRIBUTION_FILES),
        (root / "docs" / "INSTALLATION.md", "INSTALLATION.md", 0o644),
    ]
    with (
        destination.open("wb") as raw,
        gzip.GzipFile(filename="", fileobj=raw, mode="wb", mtime=0) as compressed,
        tarfile.open(
            fileobj=compressed, mode="w", format=tarfile.USTAR_FORMAT
        ) as archive,
    ):
        for source, name, mode in members:
            content = source.read_bytes()
            info = tarfile.TarInfo(str(Path(prefix) / name))
            info.size = len(content)
            info.mode = mode
            normalized_tar_info(info)
            archive.addfile(info, io.BytesIO(content))


