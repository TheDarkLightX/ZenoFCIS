def verify_packaged_workspace(
    packages_dir: Path,
    version: str,
    build_target: Path,
    environment: dict[str, str],
) -> dict[str, object]:
    build_target.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="packaged-workspace-", dir=build_target) as directory:
        return check_packaged_workspace(packages_dir, version, Path(directory), environment)


def check_packaged_workspace(
    packages_dir: Path, version: str, verification_root: Path, environment: dict[str, str],
) -> dict[str, object]:
    sources = verification_root / "sources"
    sources.mkdir(parents=True)
    commit = git_text("rev-parse", "HEAD")
    inputs = packaged_checker_inputs()
    clean = not git_text("status", "--porcelain", "--untracked-files=all")
    expected = {f"{name}-{version}.crate" for name in require_string_list(package_set(), "publish_order")}
    archives = sorted(packages_dir.glob("*.crate"))
    if {path.name for path in archives} != expected:
        raise RcError("packaged verification requires the exact declared crate set")
    package_roots: dict[str, Path] = {}
    package_evidence = []
    for archive_path in archives:
        extract_checked_crate(archive_path, sources)
        name = archive_path.stem.removesuffix(f"-{version}")
        package_root = sources / f"{name}-{version}"
        if not (package_root / "Cargo.toml").is_file():
            raise RcError(f"unpacked crate is missing Cargo.toml: {archive_path.name}")
        manifest = load_toml(package_root / "Cargo.toml")
        package = manifest.get("package", {})
        if not isinstance(package, dict) or (package.get("name"), package.get("version")) != (name, version):
            raise RcError(f"unpacked crate identity differs from its archive: {archive_path.name}")
        vcs = load_json_object(package_root / ".cargo_vcs_info.json")
        git_info = vcs.get("git")
        if not isinstance(git_info, dict) or git_info.get("sha1") != commit:
            raise RcError(f"crate source commit differs from this checkout: {archive_path.name}")
        dirty = git_info.get("dirty", False)
        if not isinstance(dirty, bool):
            raise RcError(f"crate source status is malformed: {archive_path.name}")
        package_evidence.append({"archive": archive_path.name, "sha256": sha256(archive_path),
                                 "source_clean": not dirty})
        package_roots[name] = package_root

    workspace_manifest = write_packaged_workspace_manifest(verification_root, package_roots)

    check_environment = remapped_compiler_environment(
        environment, verification_root, "/zeno-fcis-package-check",
    )
    target_dir = verification_root / "target"
    check_environment["CARGO_TARGET_DIR"] = str(target_dir)
    check_environment.update(CARGO_BUILD_JOBS="1", CARGO_INCREMENTAL="0",
                             CARGO_PROFILE_DEV_DEBUG="0", CARGO_PROFILE_TEST_DEBUG="0")
    graph = generated_application.resolve_reviewed_graph(
        verification_root,
        {(name, version): root / "Cargo.toml" for name, root in package_roots.items()},
        check_environment,
    )
    # 1. Consumer build, isolated layout: every target a consumer of a published
    #    crate builds (libraries, binaries, examples, build scripts) from the
    #    archives alone.
    run(consumer_build_command(workspace_manifest), environment=check_environment,
        cwd=verification_root)

    # 2. Packaged tests, repository layout: the same archives at crates/<name>/,
    #    plus only the verification files the reviewed manifest names. Every
    #    file a test reads outside its own package must equal that manifest.
    expected_test_inputs = load_packaged_test_inputs()
    layout_root = verification_root / "repository-layout"
    layout_roots = {name: layout_root / "crates" / name for name in package_roots}
    for name, package_root in package_roots.items():
        shutil.copytree(package_root, layout_roots[name])
    repository_inputs = stage_repository_inputs(expected_test_inputs, layout_root)
    layout_manifest = write_packaged_workspace_manifest(layout_root, layout_roots)
    layout_graph = generated_application.resolve_reviewed_graph(
        layout_root,
        {(name, version): root / "Cargo.toml" for name, root in layout_roots.items()},
        check_environment,
    )
    if layout_graph != graph:
        raise RcError("repository-layout graph differs from the isolated packaged graph")
    _, observed_test_inputs, non_test_reads = repository_layout_reads(
        layout_manifest, layout_root, check_environment,
    )
    require_packaged_test_inputs(observed_test_inputs, expected_test_inputs, non_test_reads)
    run(["cargo", "+1.97.1", "build", "--locked", "--offline", "-p", "zeno-fcis-cli",
         "--bin", "zeno-fcis"], environment=check_environment, cwd=verification_root)
    executable = verification_root / "target" / "debug" / ("zeno-fcis.exe" if os.name == "nt" else "zeno-fcis")
    application_root = verification_root / "generated-application"
    application_root.mkdir()
    app = application_root / "counter"
    run([str(executable), "new", str(app), "--template", "durable-counter"],
        environment=check_environment, cwd=application_root)
    application = generated_application.exercise_application(
        app, application_root, package_roots, version, check_environment, [str(executable)],
    )
    prepared_root = verification_root / "prepared-application"
    prepared_root.mkdir()
    prepared_app = prepared_root / "counter"
    run([str(executable), "new", str(prepared_app), "--template", "prepared-counter"],
        environment=check_environment, cwd=prepared_root)
    prepared_application = generated_application.exercise_prepared_application(
        prepared_app, prepared_root, package_roots, version, check_environment, [str(executable)],
    )
    examples = {}
    for template in generated_application.EXAMPLE_TEMPLATES:
        example_root = verification_root / f"{template}-application"
        example_root.mkdir()
        example_app = example_root / "app"
        run([str(executable), "new", str(example_app), "--template", template],
            environment=check_environment, cwd=example_root)
        examples[template] = generated_application.exercise_example_application(
            template, example_app, example_root, package_roots, version, check_environment,
            [str(executable)],
        )
    v1_consumer = generated_application.exercise_v1_consumer(
        verification_root, package_roots, version, check_environment,
    )
    compiler = run(["rustc", "+1.97.1", "-vV"], capture=True)
    if (packaged_checker_inputs() != inputs or git_text("rev-parse", "HEAD") != commit
            or (not git_text("status", "--porcelain", "--untracked-files=all")) != clean):
        raise RcError("checker inputs or source status changed during packaged verification")
    result = {
        "format": "zeno-fcis/packaged-application/1", "status": "passed",
        "source_commit": commit, "checker_source_clean": clean, "checker_inputs": inputs,
        "version": version, "compiler": compiler,
        "compiler_flags": compiler_flag_evidence(check_environment, verification_root, "<verification-root>"),
        "archives": package_evidence, "packaged_workspace_graph": graph,
        "consumer_build": {
            "layout": "sources/<crate>-<version>/, archives only",
            "command": ["cargo", "+1.97.1", "build", "--manifest-path", "<isolated-workspace>/Cargo.toml",
                        *CONSUMER_TARGET_ARGUMENTS, "--locked", "--offline", "--jobs", "1"],
        },
        "packaged_tests": {
            "layout": "crates/<crate>/ from the same archives, plus the listed verification files",
            "command": ["cargo", "+1.97.1", "test", "--manifest-path", "<repository-layout>/Cargo.toml",
                        *PACKAGED_TEST_ARGUMENTS, "--locked", "--offline", "--no-run", "--jobs", "1"],
            "test_inputs_manifest_sha256": sha256(PACKAGED_TEST_INPUTS_PATH),
            "cross_package_inputs": observed_test_inputs,
            "repository_inputs": repository_inputs,
            "standalone_tests": False,
        },
        "generator": {"package": "zeno-fcis-cli", "target": "zeno-fcis", "sha256": sha256(executable),
                      "command": ["<packaged-cli>", "new", "<new-application>", "--template", "durable-counter"]},
        "internal_manifests": [{"name": name, "version": version,
                                "path": (root / "Cargo.toml").relative_to(verification_root).as_posix()}
                               for name, root in sorted(package_roots.items())],
        "application": application,
        "prepared_application": prepared_application,
        "example_applications": examples,
        "v1_consumer": v1_consumer,
        "nonclaims": ["not a registry-only installation check", "not fresh external dependency resolution",
                      "packaged tests are not standalone: they compile only in the repository layout "
                      "with the listed verification files; the whole-repository source archive runs every test",
                      "not an independent review",
                      "not production deployment qualification", "not release authorization"],
    }
    return result


def verify_packaged(packages: Path, output: Path, version: str) -> None:
    output.mkdir(parents=True)
    target = output / ".cargo-target"
    try:
        result = verify_packaged_workspace(packages, version, target, dict(os.environ))
        write_json(output / "PACKAGED-APPLICATION.json", result)
        target.rmdir()
    except BaseException:
        # The exclusive mkdir above establishes ownership before cleanup.
        shutil.rmtree(output)
        raise
    print(f"rc-package: packaged application PASS; receipt: {output / 'PACKAGED-APPLICATION.json'}")


