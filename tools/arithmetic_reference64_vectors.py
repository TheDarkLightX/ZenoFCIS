#!/usr/bin/env python3
"""Check every 64-bit Fraction vector using A1 plus the checked width projection.

A2 signed_width_nodes_correspondence proves that projection is the production
Signed64 rule. Each concrete vector also constructs fitting input premises.
"""
from pathlib import Path
from arithmetic_proof_vectors import expression
from scalar_arithmetic_reference import boundary_cases,result


def source():
    lines=['//! Generated by tools/arithmetic_reference64_vectors.py; do not edit.',
           'use crate::arithmetic_spec::*;','use vstd::prelude::*;','verus! {']
    cases=boundary_cases(64)
    for start in range(0,len(cases),32):
        lines.append(f'pub(crate) proof fn reference64_{start//32:03}() {{')
        for case in cases[start:start+32]:
            inputs=' && '.join(f'i64::MIN as int <= ({v}int) <= i64::MAX as int' for v in case.operands)
            lines.append(f'    assert({inputs}) by(compute);')
            expr=f'match {expression(case)} {{ Some(v)=>if i64::MIN <= v <= i64::MAX {{Some(v)}}else{{None}},None=>None }}'
            value=result(case,64);expected='None::<i128>' if value is None else f'Some({value}i128)'
            lines.append(f'    assert(({expr}) == {expected}) by(compute);')
        lines.append('}')
    lines.append('}');return '\n'.join(lines)+'\n'


if __name__=='__main__':
    p=Path(__file__).resolve().parents[1]/'verification/verus/arithmetic_reference64.rs'
    p.write_text(source());print('1165 independent 64-bit expectations generated')
