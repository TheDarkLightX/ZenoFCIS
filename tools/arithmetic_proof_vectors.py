#!/usr/bin/env python3
"""Produce Verus checks of the abstract spec against every 128-bit oracle vector.

Generated proof bodies retain concrete expected outputs from the independent
Fraction reference. The reference is used only to form test expectations.
"""
from pathlib import Path
from scalar_arithmetic_reference import boundary_cases, result


def expression(case):
    a = [f'({x}int)' for x in case.operands]
    op = case.operation
    if op == 'mul':
        return f'checked_signed({a[0]}*{a[1]})'
    if op in ('div_floor','div_ceil'):
        return f'signed_division({str(op=="div_ceil").lower()},{a[0]},{a[1]})'
    if op in ('mul_div_floor','mul_div_ceil'):
        return f'signed_fused({str(op=="mul_div_ceil").lower()},{",".join(a)})'
    if op == 'products_ge':
        if len(a) == 4:
            a = [*a[:2], '1int', *a[2:], '1int']
        return f'signed_products({",".join(a)})'
    raise ValueError('uncovered oracle operation')


def source():
    lines = ['//! Generated by tools/arithmetic_proof_vectors.py; do not edit.',
             'use crate::arithmetic_spec::*;', 'use vstd::prelude::*;', 'verus! {']
    cases = boundary_cases(128)
    for start in range(0,len(cases),32):
        lines.append(f'pub(crate) proof fn reference_vectors_{start//32:03}() {{')
        for case in cases[start:start+32]:
            expected = result(case,128)
            value = 'None::<i128>' if expected is None else f'Some({expected}i128)'
            lines.append(f'    assert({expression(case)} == {value}) by(compute);')
        lines.append('}')
    lines.append('}')
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    target=Path(__file__).resolve().parents[1]/'verification/verus/arithmetic_vectors.rs'
    target.write_text(source())
    print(f'{len(boundary_cases(128))} checked expectations -> {target.name}')
