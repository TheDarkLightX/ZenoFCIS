#!/usr/bin/env python3
"""Freeze executable schema definitions from PROFILE.json; no runtime JSON parsing."""
import argparse,json,re,subprocess
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=json.loads((root/'PROFILE.json').read_text())
ids={};defs=[]
def add(name,expr):
    assert name not in ids,name
    tid=len(ids)+1;ids[name]=tid;defs.append((name,expr));return tid
def tid(n):return f'TypeId::new({ids[n]})'
def ref(n):
    if n in ids:return n
    if n.startswith('Maybe<'):
        x=ref(n[6:-1]);add(n,f'Kind::Sum {{ variants: vec![Sum::try_new(VariantId::new(0), "None", None)?, Sum::try_new(VariantId::new(1), "Some", Some({tid(x)}))?].into_boxed_slice() }}')
    elif n.startswith('Delta<'):
        x=ref(n[6:-1]);add(n,f'Kind::Sum {{ variants: vec![Sum::try_new(VariantId::new(0), "None", None)?, Sum::try_new(VariantId::new(1), "Add", Some({tid(x)}))?, Sum::try_new(VariantId::new(2), "Remove", Some({tid(x)}))?].into_boxed_slice() }}')
    elif n.startswith('('):
        xs=[ref(x) for x in n[1:-1].split(',')];add(n,'Kind::Tuple { items: vec!['+','.join(tid(x) for x in xs)+'].into_boxed_slice() }')
    elif n in ('Vector<VaultID>','BoundedVector<VaultID>'):
        add(n,f'Kind::Vector {{ element: {tid("VaultID")}, min_len: 0, max_len: b.tables[0].max_entries }}')
    else:raise ValueError(n)
    return n
def record(name,fields):
    fs=[]
    for i,(field,ty) in enumerate(fields.items(),1):
        ty=ref(ty);fs.append(f'FieldDef::try_new(FieldId::new({i}), "{field}", {tid(ty)})?')
    add(name,'Kind::Record { fields: vec!['+','.join(fs)+'].into_boxed_slice() }')
add('Unit','Kind::Unit');add('Bool','Kind::Bool')
for n,mn,mx in [('u64',0,'u64::MAX as u128'),('u32',0,'u32::MAX as u128')]:add(n,f'Kind::U128 {{ min: {mn}, max: {mx} }}')
for name in p['nominal_ids']:add(name,'Kind::Bytes { min_len: 32, max_len: 32 }')
for name in p['quantities']:
    low=1 if name in ('PositiveP','NICR') else 0
    mx='Q' if name in ('PositiveP','Rate') else 'u128::MAX'
    add(name,f'Kind::U128 {{ min: {low}, max: {mx} }}')
for name in ('AGRS e36','zUSD e36','zDEX e36','NICR-or-zero-hint'):add(name,'Kind::U128 { min: 0, max: u128::MAX }')
add('BoundedBytes','Kind::Bytes { min_len: 0, max_len: b.bounded_bytes }')
add('Status','Kind::Enum { variants: vec!['+','.join(f'EnumVariantDef::try_new(VariantId::new({i}), "{x}")?' for i,x in enumerate(('Active','ClosedOwner','ClosedLiquidation','ClosedRedemption')))+'].into_boxed_slice() }')
add('Quantity<Z|A|T>','Kind::Sum { variants: vec!['+','.join(f'Sum::try_new(VariantId::new({i}), "{name}", Some({tid(name)}))?' for i,name in enumerate(('Z','A','T')))+'].into_boxed_slice() }')
for name,fields in p['records'].items():record(name,fields)
state=['FieldDef::try_new(FieldId::new(1), "Header", '+tid('Header')+')?']
for i,t in enumerate(p['state_fields'][1:]):
    name=t['name']
    if name=='Order':kind=ref('Vector<VaultID>')
    else:
        key=ref(t['key']);value=ref(t['value']);kind='Table_'+name
        add(kind,f'Kind::Map {{ key: {tid(key)}, value: {tid(value)}, min_len: 0, max_len: b.tables[{i}].max_entries }}')
    state.append(f'FieldDef::try_new(FieldId::new({t["id"]}), "{name}", {tid(kind)})?')
add('State','Kind::Record { fields: vec!['+','.join(state)+'].into_boxed_slice() }')
for c in p['commands']:record('Command_'+c['name'],c['fields'])
add('Operation','Kind::Sum { variants: vec!['+','.join(f'Sum::try_new(VariantId::new({c["tag"]}), "{c["name"]}", Some({tid("Command_"+c["name"])}))?' for c in p['commands'])+'].into_boxed_slice() }')
record('CommandEnvelope',{'actor':'Account','nonce':'u64','pre_root':'Hash','profile_root':'Hash','operation':'Operation'})
output='// Generated by tools/schema.py from PROFILE.json. Stable IDs: schema-ids.json.\nuse super::*;\n'
output+='pub const STATE: u32 = '+str(ids['State'])+';\npub const COMMAND: u32 = '+str(ids['CommandEnvelope'])+';\n'
output+='pub fn build(b: Bounds) -> Result<Schema, SchemaError> {\nlet limits = SchemaLimits::default();\nlet mut types = Vec::new();\n'
for name,expr in defs:
    safe=re.sub('[^a-zA-Z0-9_]','_',name)
    # Include the nominal quantity's accounting unit/scale in the schema hash.
    if name in p['quantities']:safe+='_'+re.sub('[^a-zA-Z0-9_]','_',p['quantities'][name].split(' [')[0])
    output+=f'types.push(TypeDef::try_new({tid(name)}, "{safe}", {expr}, limits)?);\n'
output+='Schema::try_new("ZUSD_V1_Review", 1, TypeId::new(STATE), types, limits)\n}\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
# Formatting is part of generation, using the pinned installed formatter only.
formatted=subprocess.run(['rustfmt','+1.97.1','--edition','2024'],input=output,text=True,capture_output=True,check=True).stdout
files={root/'src/schema_generated.rs':formatted,root/'schema-ids.json':json.dumps(ids,indent=2)+'\n'}
for file,text in files.items():
    if args.check:assert file.read_text()==text,f'generated schema drift: {file}'
    else:file.write_text(text)
print(f'PASS executable schema generation: {len(ids)} closed nominal types')
