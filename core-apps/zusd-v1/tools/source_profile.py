#!/usr/bin/env python3
"""Generate/check the complete local step-4 source closure (no evaluator rewrite)."""
from pathlib import Path
import argparse,os
root=Path(__file__).resolve().parents[3]
app=root/'core-apps/zusd-v1'
dest=app/'src/application/source_closure.rs'
def generated():
 files=set(app.glob('src/**/*.rs'))|{dest,app/'Cargo.toml',app/'Cargo.lock',app/'STEP4.md',root/'Cargo.toml'}
 for name in ['zeno-fcis-codec','zeno-fcis-value','zeno-fcis-schema','zeno-fcis-collections','zeno-fcis-synthesis','zeno-fcis-core','zeno-fcis-crypto']:
  folder=root/'crates'/name
  files.add(folder/'Cargo.toml');files.update(folder.glob('src/**/*.rs'))
 files.update({root/'verification/oracle_crypto_profile.json',root/'verification/verus/authority_v2_sources.json'})
 rows=['//! Generated by tools/source_profile.py; source bytes, not an authority assertion.','#[rustfmt::skip]','pub(super) const FILES: &[(&str, &[u8])] = &[']
 for p in sorted(files):rows.append(f'    ("{p.relative_to(root).as_posix()}", include_bytes!("{os.path.relpath(p,dest.parent)}")),')
 rows.append('];')
 return '\n'.join(rows)+'\n'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();data=generated()
if args.check:
 if not dest.exists() or dest.read_text()!=data:raise SystemExit('FAIL step4 source closure drift; regenerate with tools/source_profile.py')
 print('PASS complete step4 source closure:',data.count('include_bytes!'),'files')
else:dest.write_text(data);print('Generated complete step4 source closure')
