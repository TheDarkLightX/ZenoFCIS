#!/usr/bin/env python3
"""Emit the Verus description of the compiled Spot decision program.

The output restates, node for node, the instruction list, roots and declared
input/output domains read from src/v2_contract.rs, and one lemma per block of
nodes listing each node's equation. Verus proves every equation from the
production evaluator specification; this generator decides nothing.

    python3 gen_refinement_program.py            # rewrite the Verus file
    python3 gen_refinement_program.py --check    # fail if it is stale
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import native_program
import native_terms

ROOT = native_program.APP.parents[1]
TARGET = ROOT / "verification/verus/spot_native_program.rs"
TYPES = ROOT / "verification/verus/spot_evaluator_types.rs"
EVALUATOR = ROOT / "crates/zeno-fcis-synthesis/src/finite/evaluation/mod.rs"
CHUNK = 100


def declaration(lines: list[str], name: str) -> list[str]:
    """One production enum declaration with its attributes and documentation."""
    start = next(i for i, line in enumerate(lines)
                 if line in (f"pub enum {name} {{", f"pub(crate) enum {name} {{"))
    end = lines.index("}", start)
    while lines[start - 1].startswith(("#[", "///")):
        start -= 1
    return lines[start:end + 1]


def types_text() -> str:
    """The evaluator's Domain, Op and Failure declarations, byte for byte.

    The production module also owns executable bodies outside this proof's
    closure, so the harness takes these three data declarations verbatim and
    the production specification file itself by path.
    """
    lines = EVALUATOR.read_text().split("\n")
    body = [line for name in ("Domain", "Op", "Failure") for line in declaration(lines, name) + [""]]
    digest = hashlib.sha256(EVALUATOR.read_bytes()).hexdigest()
    return "\n".join([
        "//! Generated by core-apps/zenodex-spot/tools/gen_refinement_program.py; do not edit.",
        "//! Verbatim Domain, Op and Failure declarations from",
        f"//! crates/zeno-fcis-synthesis/src/finite/evaluation/mod.rs, sha256 {digest}.",
        "#[cfg(verus_keep_ghost)]",
        "use vstd::prelude::*;",
        "",
        *body])


def op_text(op: tuple) -> str:
    name = op[0]
    if name == "Bool":
        return f"Op::Bool({'true' if op[1] else 'false'})"
    if name == "Int":
        return f"Op::Int({op[1]}i128)"
    return f"Op::{name}({', '.join(str(v) for v in op[1:])})"


def shape(k: int, op: tuple) -> str:
    """The node equality as a specification conjunct."""
    if op[0] == "ProductsGe":
        return f"products_ge_at(nodes[{k}], {', '.join(str(v) for v in op[1] + op[2])})"
    return f"nodes[{k}] == {op_text(op)}"


def term(k: int, op: tuple, nodes: tuple) -> str:
    """Node k's value as a function of the input, operator by operator."""
    t = lambda i: f"t{i}(input)"
    name = op[0]
    if name == "Input":
        return f"input[{op[1]}] as int"
    if name == "Int":
        return f"{op[1]}int"
    if name == "Bool":
        return "1int" if op[1] else "0int"
    if name == "Not":
        return f"if {t(op[1])} == 0 {{ 1int }} else {{ 0int }}"
    if name == "Select":
        return f"if {t(op[1])} == 1 {{ {t(op[2])} }} else {{ {t(op[3])} }}"
    if name in ("Add", "Sub"):
        return f"{t(op[1])} {'+' if name == 'Add' else '-'} {t(op[2])}"
    if name == "Eq":
        return f"if {t(op[1])} == {t(op[2])} {{ 1int }} else {{ 0int }}"
    if name == "Lt":
        return f"if {t(op[1])} < {t(op[2])} {{ 1int }} else {{ 0int }}"
    if name == "And":
        return f"if {t(op[1])} == 1 && {t(op[2])} == 1 {{ 1int }} else {{ 0int }}"
    if name in ("Mul", "DivFloor"):
        right = nodes[op[2]]
        if right[0] != "Int" or (name == "DivFloor" and right[1] <= 0):
            raise ValueError(f"node {k}: {name} needs a constant (positive) right operand")
        return f"{t(op[1])} {'*' if name == 'Mul' else '/'} {right[1]}int"
    if name in ("MulDivFloor", "MulDivCeil"):
        return f"{'mdf' if name == 'MulDivFloor' else 'mdc'}({t(op[1])}, {t(op[2])}, {t(op[3])})"
    if name == "ProductsGe":
        return f"if pge({', '.join(t(i) for i in op[1] + op[2])}) {{ 1int }} else {{ 0int }}"
    raise ValueError(f"node {k}: operator {name} is not in the Spot profile")


def operands(op: tuple) -> tuple[int, ...]:
    if op[0] in ("Input", "Int", "Bool"):
        return ()
    if op[0] == "ProductsGe":
        return op[1] + op[2]
    return op[1:]


def chain(native: native_program.Native) -> list[tuple[int, int, int]]:
    """(code, guard node, select node) of the first-match decision chain."""
    result, k = [], native.roots[native.decision_output]
    while native.nodes[k][0] == "Select" and native.nodes[native.nodes[k][2]][0] == "Int":
        op = native.nodes[k]
        result.append((native.nodes[op[2]][1], op[1], k))
        k = op[3]
    if native.nodes[k][0] != "Int":
        raise ValueError("decision chain does not end in a constant code")
    result.append((native.nodes[k][1], None, k))
    if [code for code, _, _ in result] != [b.code for b in native.branches]:
        raise ValueError("decision chain codes differ from the branch table")
    return result


# Guards whose meaning is stated without fixing any input (with every earlier
# accepting guard), then the inputs fixed per accepting branch: (action values,
# direction, exists, status fixed).
EARLY = (0, 1, 2, 3, 4, 7, 8)
SELECTION = {63: ((0,), 0, 0, False), 64: ((1, 2), 0, 1, True), 65: ((1, 2), 0, 1, True),
             66: ((1, 2), 1, 1, True), 67: ((1, 2), 1, 1, True), 68: ((3,), 0, 1, True),
             69: ((4,), 0, 1, True)}
# The complete conservation and mirror rechecks are not needed for the
# contract and have the largest terms; their guards are left unstated.
UNSTATED = (61, 62)


def reveals(nodes: set[int]) -> list[str]:
    return [f"    reveal(t{k});" for k in sorted(nodes)]


# The input layout spot_refinement_proof.rs is written against.
LAYOUT = ([("State", f) for f in (110, 111, 112, 113, 114, 150, 151, 152)]
          + [("State", f) for f in range(2000, 2032)]
          + [("Command", f) for f in range(120, 129)] + [("Context", 134)])


def selection(native: native_program.Native) -> list[str]:
    if list(native.bindings) != LAYOUT:
        raise ValueError("input bindings differ from the layout the proof module names")
    links = chain(native)
    guard = {code: g for code, g, _ in links}
    state = [i for i, (source, _) in enumerate(native.bindings) if source == "State"]
    accept = next(b for b in native.branches if b.accept)
    if any(b.assignments != accept.assignments for b in native.branches if b.accept):
        raise ValueError("accepting branches differ in their assignments")
    if [a.field for a in accept.assignments] != [native.bindings[i][1] for i in state]:
        raise ValueError("assignments do not follow the state field order")
    if set(SELECTION) != {b.code for b in native.branches if b.accept}:
        raise ValueError("accepting codes changed")
    # The library builds a rejecting branch's decision as the unchanged
    # pre-state with no deliveries, and refuses one that plans anything.
    if any(b.assignments or b.effects or b.outbox for b in native.branches if not b.accept):
        raise ValueError("a rejecting branch plans assignments or deliveries")
    lines = ["/// The successor state an accepting branch assigns, field by field.",
             "pub(crate) open spec fn succ(input: Seq<i128>, j: int) -> int {"]
    for j, a in enumerate(accept.assignments):
        value = f"{a.constant}int" if a.output is None else f"t{native.roots[a.output]}(input)"
        lines.append(f"    {'if' if j == 0 else '} else if'} j == {j} {{ {value}")
    lines += ["    } else { 0int }", "}", "",
              "pub(crate) open spec fn successor(input: Seq<i128>) -> Seq<int> {",
              f"    Seq::new({len(accept.assignments)}nat, |j: int| succ(input, j))", "}", "",
              "/// The output positions an accepting branch assigns, in state field order.",
              "pub(crate) open spec fn assigned(out: Seq<i128>, j: int) -> int {"]
    for j, a in enumerate(accept.assignments):
        value = f"{a.constant}int" if a.output is None else f"out[{a.output}] as int"
        lines.append(f"    {'if' if j == 0 else '} else if'} j == {j} {{ {value}")
    lines += ["    } else { 0int }", "}", "",
              "pub(crate) open spec fn accepting(code: int) -> bool {",
              "    " + " || ".join(f"code == {c}" for c in sorted(SELECTION)), "}", ""]
    root = native.roots[native.decision_output]
    lines += ["/// The decision output: the code of the first branch whose guard holds.",
              "pub(crate) open spec fn decision_code(input: Seq<i128>) -> int {", f"    t{root}(input)", "}", ""]
    for code in sorted(SELECTION):
        before = [(c, g, k) for c, g, k in links if c < code]
        # Every later link too: the rest of the chain only yields later codes.
        touched = {k for _, _, k in links} | {g for _, g, _ in before}
        touched |= {native.nodes[k][2] for _, g, k in links if g is not None}
        own = next(k for c, _, k in links if c == code)
        touched.add(own)
        ensures = [f"        t{g}(input) == 0," for _, g, _ in before]
        if guard[code] is not None:
            touched |= {guard[code], native.nodes[own][2]}
            ensures.append(f"        t{guard[code]}(input) == 1,")
        lines += [f"/// Branch {code} is selected only after every earlier guard is false.",
                  f"pub(crate) proof fn chain_{code}(input: Seq<i128>)",
                  f"    requires decision_code(input) == {code},", "    ensures", *ensures, "{",
                  *reveals(touched), "}", ""]
        # Early guards, without fixing any input.
        folder = native_terms.Folder(native, {})
        early = [c for c in EARLY if c < code] + [c for c in SELECTION if c < code]
        facts = [f"        !{native_terms.bool_text(folder.value(guard[c]))}," for c in early]
        if guard[code] is not None:
            facts.append(f"        {native_terms.bool_text(folder.value(guard[code]))},")
        needs = [f"t{guard[c]}(input) == 0" for c in early]
        if guard[code] is not None:
            needs.append(f"t{guard[code]}(input) == 1")
        lines += [f"pub(crate) proof fn early_{code}(input: Seq<i128>)",
                  f"    requires input_bounds(input), {', '.join(needs)},", "    ensures", *facts, "{",
                  *reveals(folder.visited), "}", ""]
        actions, direction, exists, active = SELECTION[code]
        for action in actions:
            fixed = {native.position("Command", 120): action, native.position("Command", 121): direction,
                     native.position("Context", 134): 1, native.position("State", 113): exists}
            if active:
                fixed[native.position("State", 114)] = 0
            folder = native_terms.Folder(native, fixed)
            facts, needs = [], [f"input[{i}] == {v}i128" for i, v in sorted(fixed.items())]
            for c, g, _ in before:
                if c in UNSTATED:
                    continue
                t = folder.value(g)
                if native_terms.is_const(t):
                    if t[1] != 0:
                        facts.append(f"        false, // guard {c} is true under these inputs")
                    continue
                needs.append(f"t{g}(input) == 0")
                facts.append(f"        !{native_terms.bool_text(t)},")
            if guard[code] is not None:
                t = folder.value(guard[code])
                needs.append(f"t{guard[code]}(input) == 1")
                if not native_terms.is_const(t):
                    facts.append(f"        {native_terms.bool_text(t)},")
            for a in accept.assignments:
                if a.output is not None:
                    facts.append(f"        t{native.roots[a.output]}(input) == "
                                 f"{native_terms.int_text(folder.value(native.roots[a.output]))},")
            lines += [f"pub(crate) proof fn sigma_{code}_{action}(input: Seq<i128>)",
                      f"    requires input_bounds(input), {', '.join(needs)},", "    ensures", *facts, "{",
                      *reveals(folder.visited), "}", ""]
    return lines


def render(native: native_program.Native, digest: str) -> str:
    domain = lambda d: f"Domain::Int {{ min: {d[0]}i128, max: {d[1]}i128 }}"
    count = len(native.nodes)
    same = lambda i: f"vals[{i}] as int == t{i}(input)"
    lines = [
        "//! Generated by core-apps/zenodex-spot/tools/gen_refinement_program.py; do not edit.",
        f"//! Source: core-apps/zenodex-spot/src/v2_contract.rs, sha256 {digest}.",
        "//! The compiled Spot decision program: its instructions, roots and declared",
        "//! domains, each node's value as a function `tK` of the input, and the proof",
        "//! from the evaluator specification that an evaluation computes exactly them.",
        "#![allow(unused_imports)]",
        "use crate::evaluation::spec::{admitted, execution, prefix, projection};",
        "use crate::evaluation::{Domain, Failure, Op};",
        "use crate::spot_refinement_base::*;",
        "use vstd::prelude::*;",
        "",
        "verus! {",
        "",
        "pub(crate) open spec fn products_ge_at(op: Op, a0: u16, a1: u16, a2: u16, b0: u16, b1: u16, b2: u16) -> bool {",
        "    match op {",
        "        Op::ProductsGe(x, y) => x[0] == a0 && x[1] == a1 && x[2] == a2 && y[0] == b0 && y[1] == b1 && y[2] == b2,",
        "        _ => false,",
        "    }",
        "}",
        "",
    ]
    blocks = list(range(0, count, CHUNK))
    # Blocks keep each conjunction shallow for the compiler front end.
    for start in blocks:
        lines.append(f"pub(crate) open spec fn spot_nodes_{start // CHUNK}(nodes: Seq<Op>) -> bool {{")
        conjuncts = [shape(k, native.nodes[k]) for k in range(start, min(start + CHUNK, count))]
        lines += [f"    {'&& ' if i else ''}{c}" for i, c in enumerate(conjuncts)]
        lines += ["}", ""]
    lines += ["pub(crate) open spec fn spot_nodes(nodes: Seq<Op>) -> bool {", f"    nodes.len() == {count}"]
    lines += [f"    && spot_nodes_{start // CHUNK}(nodes)" for start in blocks]
    lines += ["}", "", "pub(crate) open spec fn spot_roots(roots: Seq<u16>) -> bool {",
              f"    roots.len() == {len(native.roots)}"]
    lines += [f"    && roots[{i}] == {r}" for i, r in enumerate(native.roots)]
    lines += ["}", "", "pub(crate) open spec fn spot_inputs(domains: Seq<Domain>) -> bool {",
              f"    domains.len() == {len(native.inputs)}"]
    lines += [f"    && domains[{i}] == {domain(d)}" for i, d in enumerate(native.inputs)]
    lines += ["}", "", "pub(crate) open spec fn spot_outputs(domains: Seq<Domain>) -> bool {",
              f"    domains.len() == {len(native.outputs)}"]
    lines += [f"    && domains[{i}] == {domain(d)}" for i, d in enumerate(native.outputs)]
    lines += ["}", "", "/// Every admitted input lies in its declared domain.",
              "pub(crate) open spec fn input_bounds(input: Seq<i128>) -> bool {",
              f"    input.len() == {len(native.inputs)}"]
    lines += [f"    && {lo}i128 <= input[{i}] <= {hi}i128" for i, (lo, hi) in enumerate(native.inputs)]
    lines += ["}", ""]
    for k, op in enumerate(native.nodes):
        lines += ["#[verifier::opaque]",
                  f"pub(crate) open spec fn t{k}(input: Seq<i128>) -> int {{ {term(k, op, native.nodes)} }}"]
    lines.append("")
    # One lemma per node: its instruction, its successful evaluation and its
    # operands' values give its own value.
    for k, op in enumerate(native.nodes):
        needs = "".join(f" {same(i)}," for i in operands(op))
        body = [f"    reveal(t{k});"] + [f"    reveal(t{i});" for i in operands(op) if native.nodes[i][0] == "Int"]
        body += {"MulDivFloor": ["    reveal(mdf);"], "MulDivCeil": ["    reveal(mdc);"],
                 "ProductsGe": ["    reveal(pge);"]}.get(op[0], [])
        if op[0] == "DivFloor":
            body.append(f"    positive_floor(vals[{op[1]}], vals[{op[2]}]);")
        lines += [f"pub(crate) proof fn n{k}(nodes: Seq<Op>, input: Seq<i128>, vals: Seq<i128>)",
                  f"    requires vals.len() == {count}, {shape(k, op)}, node_ok(nodes, input, vals, {k}),{needs}",
                  f"    ensures {same(k)},", "{", *body, "}", ""]
    for start in blocks:
        block = range(start, min(start + CHUNK, count))
        external = sorted({i for k in block for i in operands(native.nodes[k]) if i < start})
        calls = []
        for k in block:
            calls += [f"    assert(node_ok(nodes, input, vals, {k}));", f"    n{k}(nodes, input, vals);"]
        lines += [f"pub(crate) proof fn block_{start // CHUNK}(nodes: Seq<Op>, input: Seq<i128>, vals: Seq<i128>)",
                  f"    requires nodes.len() == {count}, spot_nodes_{start // CHUNK}(nodes), evaluated(nodes, input, vals),",
                  *[f"        {same(i)}," for i in external],
                  "    ensures", *[f"        {same(k)}," for k in block], "{", *calls, "}", ""]
    lines += ["/// A successful evaluation computes every root's term.",
              "pub(crate) proof fn values_are_terms(nodes: Seq<Op>, input: Seq<i128>, vals: Seq<i128>)",
              "    requires spot_nodes(nodes), evaluated(nodes, input, vals),",
              "    ensures", *[f"        {same(r)}," for r in sorted(set(native.roots))], "{"]
    lines += [f"    block_{start // CHUNK}(nodes, input, vals);" for start in blocks]
    lines += ["}", "",
              "/// The program's outputs on any input the production evaluator specification",
              "/// accepts: the input is in its declared domains and each output is its root's term.",
              "pub(crate) proof fn program_terms(inputs: Seq<Domain>, outputs: Seq<Domain>, nodes: Seq<Op>,",
              "    roots: Seq<u16>, input: Seq<i128>, out: Seq<i128>)",
              "    requires spot_nodes(nodes), spot_roots(roots), spot_inputs(inputs), spot_outputs(outputs),",
              "        execution(inputs, outputs, nodes, roots, input) == Ok::<Seq<i128>, Failure>(out),",
              f"    ensures input_bounds(input), out.len() == {len(native.roots)},",
              *[f"        out[{i}] as int == t{r}(input)," for i, r in enumerate(native.roots)],
              "{",
              "    assert(admitted(inputs, input));",
              f"    assert forall|i: int| 0 <= i < {len(native.inputs)} implies "
              "#[trigger] crate::evaluation::spec::contains(inputs[i], input[i]) by {}",
              "    match prefix(nodes, input, nodes.len()) {",
              "        Err(_) => {},",
              "        Ok(vals) => {",
              "            prefix_evaluated(nodes, input, nodes.len(), vals);",
              "            values_are_terms(nodes, input, vals);",
              "            projection_values(vals, roots, roots.len(), out);",
              "        },",
              "    }",
              "}", ""]
    lines += selection(native)
    lines += ["}", ""]
    return "\n".join(lines)


def outputs(source: Path = native_program.SOURCE, target: Path = TARGET) -> dict[Path, str]:
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    return {target: render(native_program.load(source), digest), TYPES: types_text()}


def stale(source: Path = native_program.SOURCE, target: Path = TARGET) -> list[str]:
    """Generated files that differ from what the current sources give."""
    return [str(path) for path, text in outputs(source, target).items()
            if not path.is_file() or path.read_text() != text]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=native_program.SOURCE)
    parser.add_argument("--out", type=Path, default=TARGET)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        for path in stale(args.source, args.out):
            print(f"stale: {path}", file=sys.stderr)
        return 1 if stale(args.source, args.out) else 0
    for path, text in outputs(args.source, args.out).items():
        path.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
